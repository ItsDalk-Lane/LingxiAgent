#!/usr/bin/env node
"use strict";

/**
 * R11：把保留的 Node 外围 worker 打成 Tauri 随包资源。
 *
 * 业主裁决：外围 worker 保留 Node 实现，应用携带固定 Node 运行时。
 * 本脚本只打包 worker 入口与运行素材，不打包旧 Agent core/server：
 * - Office 文档读取、媒体即梦解析、Bridge SDK、PTC、AST/LSP 各自单文件 ESM；
 * - 依赖尽量内联，避免安装包再携带 node_modules；
 * - 复制主题/封面给 Office worker，复制 ast-grep 给 AST 工具；
 * - 输出目录在 .gitignore 内，不进入 git。
 *
 * 运行前置：`npm run build:renderer` 已产出 dist-renderer/themes。
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildSync } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RESOURCE_DIR = path.join(ROOT, "desktop", "src-tauri", "resources");
const WORKERS_DIR = path.join(RESOURCE_DIR, "workers");
const OFFICE_DIR = path.join(RESOURCE_DIR, "office");
const BIN_DIR = path.join(RESOURCE_DIR, "bin");

const WORKERS = [
  {
    name: "office-document-worker",
    entry: "scripts/office-document-worker.ts",
    forbidden: /(?:^|\/)core\//,
    forbiddenReason: "Office worker unexpectedly includes old core execution code",
  },
  {
    name: "media-jimeng-worker",
    entry: "scripts/media-jimeng-worker.ts",
    forbidden: /(?:^|\/)core\/(?:agent|engine|media\/universal-media-manager|bridge-session-manager)(?:\.|\/)/,
    forbiddenReason: "Media worker unexpectedly includes an execution loop",
  },
  {
    name: "bridge-sdk-worker",
    entry: "scripts/bridge-sdk-worker.ts",
    forbidden: /(?:^|\/)core\/(?:agent|engine|bridge-session-manager)/,
    forbiddenReason: "Bridge SDK worker unexpectedly includes the old execution loop",
  },
  {
    name: "bridge-sdk-diagnostic",
    entry: "scripts/bridge-sdk-diagnostic.ts",
    forbidden: /(?:^|\/)core\/(?:agent|engine|bridge-session-manager)/,
    forbiddenReason: "Bridge diagnostic worker unexpectedly includes the old execution loop",
  },
  {
    name: "ptc-worker",
    entry: "scripts/rust-tauri/r08-ptc-worker.mjs",
    forbidden: /(?:^|\/)core\/(?:agent|engine)/,
    forbiddenReason: "PTC worker unexpectedly includes the old execution loop",
  },
  {
    name: "lsp-worker",
    entry: "scripts/rust-tauri/r08-lsp-worker.mjs",
    forbidden: /(?:^|\/)core\/(?:agent|engine)/,
    forbiddenReason: "LSP worker unexpectedly includes the old execution loop",
  },
];

function bundleWorker(worker) {
  fs.mkdirSync(WORKERS_DIR, { recursive: true });
  const outfile = path.join(WORKERS_DIR, `${worker.name}.mjs`);
  const result = buildSync({
    absWorkingDir: ROOT,
    entryPoints: [path.join(ROOT, worker.entry)],
    outfile,
    bundle: true,
    platform: "node",
    target: "node24",
    format: "esm",
    metafile: true,
    logLevel: "warning",
    banner: {
      js: "// Generated by scripts/stage-tauri-workers.mjs — do not edit.\n"
        + "import { createRequire as __lingxiCreateRequire } from 'node:module';\n"
        + "const require = __lingxiCreateRequire(import.meta.url);",
    },
  });
  const forbidden = Object.keys(result.metafile.inputs)
    .filter((file) => !file.startsWith("node_modules/"))
    .filter((file) => worker.forbidden.test(file));
  if (forbidden.length > 0) {
    throw new Error(`${worker.forbiddenReason}: ${forbidden.slice(0, 5).join(", ")}`);
  }
  if (!fs.existsSync(outfile) || fs.statSync(outfile).size === 0) {
    throw new Error(`worker output missing: ${outfile}`);
  }
  return { name: worker.name, outfile, bytes: fs.statSync(outfile).size, inputs: Object.keys(result.metafile.inputs).length };
}

function copyDirectory(source, target) {
  if (!fs.existsSync(source) || !fs.statSync(source).isDirectory()) {
    throw new Error(`required resource directory missing: ${source}`);
  }
  fs.rmSync(target, { recursive: true, force: true });
  fs.cpSync(source, target, { recursive: true, verbatimSymlinks: true });
}

function copyFile(source, target, mode = 0o755) {
  if (!fs.existsSync(source) || !fs.statSync(source).isFile()) {
    throw new Error(`required resource file missing: ${source}`);
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(source, target);
  fs.chmodSync(target, mode);
}

function main() {
  fs.mkdirSync(RESOURCE_DIR, { recursive: true });
  fs.rmSync(WORKERS_DIR, { recursive: true, force: true });
  fs.mkdirSync(WORKERS_DIR, { recursive: true });

  const workers = WORKERS.map(bundleWorker);

  const themes = path.join(ROOT, "desktop", "dist-renderer", "themes");
  const covers = path.join(ROOT, "desktop", "src", "assets", "cover-gallery");
  copyDirectory(themes, path.join(OFFICE_DIR, "themes"));
  copyDirectory(covers, path.join(OFFICE_DIR, "covers"));

  const astGrepSource = path.join(ROOT, "bundled-bin", `${process.platform === "darwin" ? "mac" : "linux"}-${process.arch}`, "ast-grep");
  copyFile(astGrepSource, path.join(BIN_DIR, "ast-grep"));

  const manifest = {
    schema: "lingxi.r11.tauri-workers.v1",
    generatedAt: new Date().toISOString(),
    nodeRuntime: "resources/node/bin/node",
    workers: workers.map(({ name, outfile, bytes, inputs }) => ({ name, file: path.basename(outfile), bytes, inputs })),
    officeThemes: "resources/office/themes",
    officeCovers: "resources/office/covers",
    astGrep: "resources/bin/ast-grep",
  };
  fs.writeFileSync(path.join(RESOURCE_DIR, "workers", "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf-8");
  for (const worker of workers) {
    console.log(`[workers] ${worker.name}: ${(worker.bytes / 1024 / 1024).toFixed(2)} MiB (${worker.inputs} inputs)`);
  }
  console.log(`[workers] staged under ${RESOURCE_DIR}`);
}

try {
  main();
} catch (error) {
  console.error(`[workers] ${error && error.message ? error.message : error}`);
  process.exitCode = 1;
}
