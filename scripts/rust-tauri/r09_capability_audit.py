# ── 基础设施 ────────────────────────────────────────────────────────────


def case(name: str, ok: bool, detail=None) -> bool:
    CASES.append({"case": name, "ok": bool(ok), "actual": 1 if ok else 0, "detail": detail})
    return bool(ok)


def log(message: str) -> None:
    print(message, flush=True)
    LOGS.append(message)


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def rel(path: Path) -> str:
    """仓库内相对路径；策略/证据目录在仓库外时退化为绝对路径（不抛错）。"""
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def strip_rust_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def strip_rust_cfg_test(text: str) -> str:
    """删除 `#[cfg(test)]` 修饰的 item（测试模块里的 dev URL 不算生产配置）。"""
    pattern = re.compile(r"#\s*\[\s*cfg\s*\(\s*test\s*\)\s*\]")
    while True:
        match = pattern.search(text)
        if not match:
            return text
        brace = text.find("{", match.end())
        if brace < 0:
            text = text[: match.start()]
            continue
        depth = 0
        end = len(text)
        for index in range(brace, len(text)):
            char = text[index]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    end = index + 1
                    break
        text = text[: match.start()] + text[end:]


def bracket_body(text: str, start: int) -> str | None:
    if start >= len(text) or text[start] != "[":
        return None
    depth = 0
    for index in range(start, len(text)):
        char = text[index]
        if char == "[":
            depth += 1
        elif char == "]":
            depth -= 1
            if depth == 0:
                return text[start + 1:index]
    return None


# ── 解析：注册面 ─────────────────────────────────────────────────────────


def parse_generate_handler() -> list[str]:
    text = strip_rust_comments(read(TAURI / "src/lib.rs"))
    commands: list[str] = []
    for marker in re.finditer(r"generate_handler!", text):
        body = bracket_body(text, text.find("[", marker.end()))
        if body is None:
            continue
        for item in body.split(","):
            item = item.strip()
            if not item:
                continue
            name = item.split("::")[-1].strip()
            if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
                commands.append(name)
    return sorted(set(commands))


def parse_build_manifest() -> list[str]:
    """解析 build.rs 的 AppManifest 命令集合。

    兼容两种写法：内联 `commands(&["a","b"])` 与构造 `Vec<&str>` 后
    `commands(&commands)`（D11 需要按 feature 条件追加 debug 命令）。
    """
    text = strip_rust_comments(read(TAURI / "build.rs"))
    match = re.search(r"AppManifest::new\(\)\s*\.commands\(\s*&?\[(.*?)\]", text, re.S)
    if match:
        return sorted(set(re.findall(r'"([A-Za-z0-9_\-]+)"', match.group(1))))
    names = set(re.findall(r'"([a-z][a-z0-9_]{3,})"', text))
    return sorted(names)


def parse_debug_invoke_commands() -> list[str]:
    text = strip_rust_comments(read(TAURI / "src/native/install.rs"))
    match = re.search(r"DEBUG_INVOKE_COMMANDS[^=]*=\s*&?\[(.*?)\];", text, re.S)
    if not match:
        return []
    return sorted(set(re.findall(r'"([A-Za-z0-9_\-]+)"', match.group(1))))


def parse_permissions() -> dict[str, dict]:
    permissions: dict[str, dict] = {}
    for path in sorted((TAURI / "permissions").glob("**/*.toml")):
        text = read(path)
        for block in re.finditer(r"\[\[permission\]\](.*?)(?=\[\[permission\]\]|\Z)", text, re.S):
            body = block.group(1)
            identifier = re.search(r'identifier\s*=\s*"([^"]+)"', body)
            if not identifier:
                continue
            allow = re.search(r"commands\.allow\s*=\s*\[(.*?)\]", body, re.S)
            deny = re.search(r"commands\.deny\s*=\s*\[(.*?)\]", body, re.S)
            permissions[identifier.group(1)] = {
                "file": str(path.relative_to(ROOT)),
                "allow": re.findall(r'"([^"]+)"', allow.group(1)) if allow else [],
                "deny": re.findall(r'"([^"]+)"', deny.group(1)) if deny else [],
            }
    return permissions


def parse_capabilities() -> dict[str, dict]:
    capabilities: dict[str, dict] = {}
    for path in sorted((TAURI / "capabilities").glob("*.json")):
        value = json.loads(read(path))
        capabilities[value.get("identifier", path.stem)] = {
            "file": str(path.relative_to(ROOT)),
            "windows": value.get("windows") or [],
            "webviews": value.get("webviews") or [],
            "permissions": value.get("permissions") or [],
            "platforms": value.get("platforms"),
        }
    return capabilities


def parse_app_acl_commands() -> set[str]:
    path = TAURI / "gen/schemas/acl-manifests.json"
    if not path.is_file():
        return set()
    try:
        manifest = json.loads(read(path))
    except json.JSONDecodeError:
        return set()
    app = manifest.get("__app-acl__") or {}
    commands: set[str] = set()
    for permission in (app.get("permissions") or {}).values():
        commands.update((permission.get("commands") or {}).get("allow") or [])
        commands.update((permission.get("commands") or {}).get("deny") or [])
    return commands


def load_acl_manifests() -> dict:
    path = TAURI / "gen/schemas/acl-manifests.json"
    if not path.is_file():
        return {}
    try:
        return json.loads(read(path))
    except json.JSONDecodeError:
        return {}


def plugin_permission_leaves(permission_id: str, manifests: dict | None = None) -> set[str] | None:
    """把插件权限（含 *:default 聚合）展开为最终 leaf 标识；未知插件返回 None。"""
    manifests = manifests if manifests is not None else load_acl_manifests()
    # 权限标识形如 `plugin:permission`，而 Tauri core 插件本身带命名空间
    # （`core:event:default` → plugin=`core:event`, permission=`default`）。
    # 按最长已注册插件前缀切分，避免把 `core:event` 误切成 `core`+`event:default`。
    plugin = None
    rest = ""
    for candidate in sorted(manifests, key=len, reverse=True):
        if permission_id.startswith(candidate + ":"):
            plugin = candidate
            rest = permission_id[len(candidate) + 1:]
            break
    if not plugin or not rest:
        return None
    entry = manifests.get(plugin)
    if not isinstance(entry, dict):
        return None
    if rest == "default":
        default = entry.get("default_permission") or {}
        children = default.get("permissions") or []
        leaves: set[str] = set()
        for child in children:
            full = child if ":" in child else f"{plugin}:{child}"
            resolved = plugin_permission_leaves(full, manifests)
            if resolved is None:
                return None
            leaves |= resolved
        return leaves
    permission = (entry.get("permissions") or {}).get(rest)
    if isinstance(permission, dict):
        leaves = {f"{plugin}:{rest}"}
        for child in permission.get("permissions") or []:
            full = child if ":" in child else f"{plugin}:{child}"
            resolved = plugin_permission_leaves(full, manifests)
            if resolved is None:
                return None
            leaves |= resolved
        return leaves
    permission_set = (entry.get("permission_sets") or {}).get(rest)
    if isinstance(permission_set, dict):
        leaves = set()
        for child in permission_set.get("permissions") or []:
            full = child if ":" in child else f"{plugin}:{child}"
            resolved = plugin_permission_leaves(full, manifests)
            if resolved is None:
                return None
            leaves |= resolved
        return leaves
    return None


# ── 解析：窗口 label / 范围展开 ──────────────────────────────────────────


def parse_native_window_patterns() -> dict[str, str]:
    """窗口 label 角色唯一来源：`src/native/window_labels.rs`。

    返回 {role: labelPattern}，labelPattern 只含固定 label 或 `prefix*` glob。
    """
    fallback = {
        "main": "main",
        "settings": "settings",
        "quick-chat": "quick-chat",
        "browser-viewer": "browser-viewer",
        "splash": "splash",
        "onboarding": "onboarding",
        "viewer-*": "viewer-*",
        "skill-viewer-*": "skill-viewer-*",
    }
    text = read(TAURI / "src/native/window_labels.rs")
    if not text:
        return fallback
    patterns: dict[str, str] = {}
    const_names = [
        ("MAIN", "main"), ("SETTINGS", "settings"), ("QUICK_CHAT", "quick-chat"),
        ("BROWSER_VIEWER", "browser-viewer"), ("SPLASH", "splash"),
        ("ONBOARDING", "onboarding"),
    ]
    for const, role in const_names:
        match = re.search(rf'pub const {const}\s*:\s*&str\s*=\s*"([^"]+)"', text)
        if match:
            patterns[role] = match.group(1)
    for const, role in (("VIEWER_PREFIX", "viewer"), ("SKILL_VIEWER_PREFIX", "skill-viewer")):
        match = re.search(rf'pub const {const}\s*:\s*&str\s*=\s*"([^"]+)"', text)
        if match:
            patterns[f"{role}-*"] = match.group(1) + "*"
    return patterns or fallback


def concrete_label(pattern: str) -> str:
    return pattern.replace("*", "probe") if "*" in pattern else pattern


def parse_csp(csp: str) -> dict[str, list[str]]:
    directives: dict[str, list[str]] = {}
    for part in (csp or "").split(";"):
        tokens = part.strip().split()
        if tokens:
            directives[tokens[0].lower()] = tokens[1:]
    return directives


def expand_permissions(capabilities: dict[str, dict], permissions: dict[str, dict],
                       labels: list[str], excluded_capabilities: set[str] | None = None,
                       manifests: dict | None = None) -> dict[str, dict]:
    excluded = excluded_capabilities or set()
    manifests = manifests if manifests is not None else load_acl_manifests()
    expanded: dict[str, dict] = {}
    for label in labels:
        allowed: set[str] = set()
        sources: list[str] = []
        plugin_refs: set[str] = set()
        plugin_leaves: set[str] = set()
        unknown: list[dict] = []
        for identifier, capability in capabilities.items():
            if identifier in excluded:
                continue
            matched = any(fnmatch.fnmatchcase(label, pattern) for pattern in capability["windows"])
            if not matched:
                continue
            sources.append(identifier)
            for permission in capability["permissions"]:
                if permission in permissions:
                    allowed.update(permissions[permission]["allow"])
                    continue
                if permission.startswith("allow-") or permission.startswith("deny-"):
                    # 自定义命令权限但未在 permissions/*.toml 中声明（陈旧/拼写错误）。
                    if permission not in permissions:
                        unknown.append({"capability": identifier, "permission": permission,
                                        "kind": "custom-unknown"})
                    continue
                leaves = plugin_permission_leaves(permission, manifests)
                if leaves is None:
                    unknown.append({"capability": identifier, "permission": permission,
                                    "kind": "plugin-unknown"})
                    continue
                plugin_refs.add(permission)
                plugin_leaves |= leaves
        expanded[label] = {
            "capabilities": sources,
            "commands": sorted(allowed),
            "pluginPermissions": sorted(plugin_refs),
            "pluginLeaves": sorted(plugin_leaves),
            "unknownPermissions": unknown,
        }
    return expanded


def dangerous_plugin_leaves(leaves: set[str]) -> list[str]:
    hits = set()
    for leaf in leaves:
        for pattern in DANGEROUS_PLUGIN_PATTERNS:
            if fnmatch.fnmatchcase(leaf, pattern):
                hits.add(leaf)
                break
    return sorted(hits)


# ── policy 读取与结构校验 ────────────────────────────────────────────────


def load_policy(path: Path) -> dict | None:
    if not path.is_file():
        return None
    return json.loads(read(path))


def validate_policy_shape(policy: dict) -> list[str]:
    errors: list[str] = []
    if policy.get("schema") != "lingxi.r09.command-policy.v1":
        errors.append(f"schema 应为 lingxi.r09.command-policy.v1，实为 {policy.get('schema')!r}")
    windows = policy.get("windows")
    if not isinstance(windows, dict) or not windows:
        errors.append("windows 必须是非空对象")
        windows = {}
    for label, spec in windows.items():
        if not isinstance(spec, dict):
            errors.append(f"windows[{label}] 必须是对象")
            continue
        for field in ("allowedCommands", "allowedPluginPermissions", "deniedCommands"):
            value = spec.get(field)
            if not isinstance(value, list) or any(not isinstance(item, str) for item in value):
                errors.append(f"windows[{label}].{field} 必须是字符串数组")
        allowed = set(spec.get("allowedCommands") or [])
        denied = set(spec.get("deniedCommands") or [])
        overlap = allowed & denied
        if overlap:
            errors.append(f"windows[{label}] allowedCommands 与 deniedCommands 冲突: {sorted(overlap)}")
    protected = policy.get("protectedCommands")
    if not isinstance(protected, dict):
        errors.append("protectedCommands 必须是 command → {windows, reason} 对象")
    else:
        for command, spec in protected.items():
            if not isinstance(spec, dict) or not isinstance(spec.get("windows"), list):
                errors.append(f"protectedCommands[{command}] 缺少 windows 数组")
    gap = policy.get("gapLedger")
    if not isinstance(gap, dict):
        errors.append("gapLedger 必须是对象")
    else:
        if not isinstance(gap.get("pendingImplementation", {}), dict):
            errors.append("gapLedger.pendingImplementation 必须是对象")
        if not isinstance(gap.get("pendingWindowGrants", {}), dict):
            errors.append("gapLedger.pendingWindowGrants 必须是对象")
    for key in ("releaseDeniedCommands", "devOnlyCommands", "forbiddenCommandPatterns"):
        if not isinstance(policy.get(key), list):
            errors.append(f"{key} 必须是数组")
    if not isinstance(policy.get("securityBaseline"), dict):
        errors.append("securityBaseline 必须是对象")
    return errors


# ── 主流程 ──────────────────────────────────────────────────────────────


def main() -> int:
    started = time.time()
    evidence = None
    if "--evidence" in sys.argv:
        evidence = Path(sys.argv[sys.argv.index("--evidence") + 1])
        evidence = evidence if evidence.is_absolute() else ROOT / evidence
        evidence.mkdir(parents=True, exist_ok=True)
    policy_path = (Path(sys.argv[sys.argv.index("--policy") + 1])
                   if "--policy" in sys.argv else POLICY_PATH)
    policy_path = policy_path if policy_path.is_absolute() else ROOT / policy_path
    policy = load_policy(policy_path)

    registered_all = parse_generate_handler()
    manifest_all = parse_build_manifest()
    permissions = parse_permissions()
    capabilities = parse_capabilities()
    acl_commands_all = parse_app_acl_commands()
    native_patterns = parse_native_window_patterns()
    manifests = load_acl_manifests()

    # D11：debug/test 命令由 r09-test-hooks feature 注册，不属于交付 release 命令面。
    # 四集合一致性、窗口展开、缺口账本一律按 release 命令集比较；debug 命令单独
    # 由 caps::debug-commands-declared-dev-only / delivery receipt 检查覆盖。
    dev_commands: set[str] = set()
    if policy is not None:
        dev_commands = set(policy.get("devOnlyCommands") or [])
    if not dev_commands:
        dev_commands = set(parse_debug_invoke_commands())
    registered = [c for c in registered_all if c not in dev_commands]
    manifest = [c for c in manifest_all if c not in dev_commands]
    acl_commands = {c for c in acl_commands_all if c not in dev_commands}
    for name, table in permissions.items():
        table["allow"] = [c for c in table["allow"] if c not in dev_commands]
        table["deny"] = [c for c in table["deny"] if c not in dev_commands]
    labels = [concrete_label(pattern) for pattern in native_patterns.values()]
    all_expanded = expand_permissions(capabilities, permissions, labels, manifests=manifests)
    permission_allow_commands = sorted({cmd for perm in permissions.values() for cmd in perm["allow"]})

    log(f"registered={len(registered)} manifest={len(manifest)} "
        f"permissions={len(permissions)} capabilities={len(capabilities)} "
        f"windowPatterns={len(native_patterns)} policy={'yes' if policy else 'no'} "
        f"devOnlyCommands={sorted(dev_commands)}")

    # ── 四集合一致性（policy 无关；release 命令集） ───────────────────
    case("caps::registered-commands-nonzero", len(registered) > 0, registered)
    case("caps::invoke-handler-equals-build-manifest", registered == manifest,
         {"onlyInvokeHandler": sorted(set(registered) - set(manifest)),
          "onlyBuildManifest": sorted(set(manifest) - set(registered))})
    case("caps::each-command-has-permission",
         set(registered) <= set(permission_allow_commands),
         {"missingPermission": sorted(set(registered) - set(permission_allow_commands))})
    case("caps::each-permission-command-registered",
         set(permission_allow_commands) <= set(registered),
         {"orphanPermissionCommands": sorted(set(permission_allow_commands) - set(registered))})
    if acl_commands:
        case("caps::acl-manifest-covers-registered",
             set(registered) <= acl_commands,
             {"missingFromAcl": sorted(set(registered) - acl_commands)})
    case("caps::capability-windows-nonempty",
         all(cap["windows"] for cap in capabilities.values()),
         {identifier: cap["windows"] for identifier, cap in capabilities.items()})
    remote_like = []
    for identifier, capability in capabilities.items():
        for pattern in capability["windows"]:
            lowered = pattern.lower()
            if pattern.strip() == "*" or "://" in lowered or "http" in lowered \
                    or "remote" in lowered or "webview" in lowered:
                remote_like.append({"capability": identifier, "windowPattern": pattern})
    case("caps::capability-windows-no-remote-content-label", not remote_like, remote_like)

    if policy is None:
        # 无 policy：只做危险插件权限 fallback 静态检查；不冒充策略通过。
        dangerous = []
        for label, expansion in all_expanded.items():
            hits = dangerous_plugin_leaves(set(expansion["pluginLeaves"]))
            if hits:
                dangerous.append({"window": label, "permissions": hits})
        case("caps::no-dangerous-plugin-permissions-fallback", not dangerous, dangerous)
        case("caps::policy-present", False,
             {"expected": rel(policy_path),
              "note": "T06 授权策略文件尚未建立；静态检查通过不代表 A11 通过"})
        failed = [row["case"] for row in CASES if not row["ok"]]
        if failed == ["caps::policy-present"]:
            status, exit_code = "PENDING_POLICY", 3
        else:
            status, exit_code = "FAIL", 2
        return finish(evidence, status, exit_code, started, registered, manifest,
                      capabilities, permission_allow_commands, all_expanded, policy,
                      {"policy": "absent"})

    # ── policy 结构/标签一致性 ───────────────────────────────────────
    shape_errors = validate_policy_shape(policy)
    case("caps::policy-schema-valid", not shape_errors, shape_errors)

    expected_patterns = set(native_patterns.values())
    policy_patterns = set((policy.get("windows") or {}).keys())
    case("caps::policy-window-labels-match-native", expected_patterns == policy_patterns,
         {"onlyNative": sorted(expected_patterns - policy_patterns),
          "onlyPolicy": sorted(policy_patterns - expected_patterns)})

    # ── dev-only capability 排除 + release 展开 ──────────────────────
    dev_config = policy.get("devOnlyCapabilities") or {}
    dev_identifiers = set(dev_config.get("identifiers") or [])
    dev_commands = set(dev_config.get("grantedCommands") or []) | set(policy.get("devOnlyCommands") or [])
    present_dev = sorted(dev_identifiers & set(capabilities))
    dev_expansion = expand_permissions(capabilities, permissions,
                                       [concrete_label(p) for p in dev_identifiers],
                                       manifests=manifests) if present_dev else {}
    release_expanded = expand_permissions(capabilities, permissions, labels,
                                          excluded_capabilities=dev_identifiers,
                                          manifests=manifests)
    dev_granted: set[str] = set()
    for expansion in dev_expansion.values():
        dev_granted.update(expansion["commands"])
    case("caps::dev-only-capability-grants-only-dev-commands",
         dev_granted <= dev_commands,
         {"presentDevCapabilities": present_dev,
          "devGranted": sorted(dev_granted),
          "undeclared": sorted(dev_granted - dev_commands)})

    windows_policy = policy.get("windows") or {}
    gap = policy.get("gapLedger") or {}
    pending_impl = set((gap.get("pendingImplementation") or {}).keys())
    pending_grants = {label: set((spec or {}).get("commands") or [])
                      for label, spec in (gap.get("pendingWindowGrants") or {}).items()}
    del pending_grants  # 逐窗口在下面重算；这里只校验结构

    comparison: dict[str, dict] = {}
    window_errors: list[str] = []
    dangerous_any: list[dict] = []
    unknown_any: list[dict] = []
    for pattern, spec in sorted(windows_policy.items()):
        matched_labels = [label for label in labels if fnmatch.fnmatchcase(label, pattern)]
        if not matched_labels:
            case(f"caps::window-matched::{pattern}", False,
                 {"reason": "native/window_labels.rs 没有匹配该模式的窗口 label"})
            continue
        label = matched_labels[0]
        actual = release_expanded[label]
        allowed = set(spec.get("allowedCommands") or [])
        declared_grants = set(((gap.get("pendingWindowGrants") or {}).get(pattern) or {})
                              .get("commands") or [])
        extra = sorted(set(actual["commands"]) - allowed)
        missing = sorted(allowed - set(actual["commands"]))
        undeclared_missing = sorted(set(missing) - pending_impl - declared_grants)
        ok = not extra and not undeclared_missing
        if not ok:
            window_errors.append(pattern)
        case(f"caps::window-union-equals-policy::{pattern}", ok,
             {"commandWindows": sorted(actual["capabilities"]),
              "extraPrivilege": extra,
              "missingUndeclared": undeclared_missing,
              "declaredPending": sorted(set(missing) & (pending_impl | declared_grants))})

        allowed_plugins = set(spec.get("allowedPluginPermissions") or [])
        plugin_extra = sorted(set(actual["pluginPermissions"]) - allowed_plugins)
        case(f"caps::window-plugin-permissions::{pattern}", not plugin_extra,
             {"actual": sorted(actual["pluginPermissions"]),
              "allowed": sorted(allowed_plugins),
              "extraPluginPermissions": plugin_extra})

        denied_hit = sorted(set(actual["commands"]) & set(spec.get("deniedCommands") or []))
        case(f"caps::window-denied-commands::{pattern}", not denied_hit, denied_hit)

        hits = dangerous_plugin_leaves(set(actual["pluginLeaves"]))
        if hits:
            dangerous_any.append({"window": pattern, "leaves": hits})
        if actual["unknownPermissions"]:
            unknown_any.extend(actual["unknownPermissions"])
        comparison[pattern] = {
            "nativeLabel": label,
            "capabilities": sorted(actual["capabilities"]),
            "actualCommands": actual["commands"],
            "allowedCommands": sorted(allowed),
            "extraPrivilege": extra,
            "missing": missing,
            "declaredPending": sorted(set(missing) & (pending_impl | declared_grants)),
            "undeclaredMissing": undeclared_missing,
            "actualPluginPermissions": sorted(actual["pluginPermissions"]),
            "pluginLeaves": actual["pluginLeaves"],
            "dangerousPluginLeaves": hits,
        }

    case("caps::no-dangerous-plugin-permissions", not dangerous_any, dangerous_any)
    case("caps::capabilities-reference-known-permissions", not unknown_any, unknown_any)

    # 多 capability 叠加场景必须真实存在（A11/OQ-10）。
    for pattern, spec in (policy.get("stackingWindows") or {}).items():
        minimum = int(spec.get("minCapabilities") or 1)
        matched = [label for label in labels if fnmatch.fnmatchcase(label, pattern)]
        count = len(release_expanded[matched[0]]["capabilities"]) if matched else 0
        case(f"caps::window-stacking::{pattern}", count >= minimum,
             {"capabilities": release_expanded[matched[0]]["capabilities"] if matched else [],
              "minCapabilities": minimum})

    # ── 缺口账本严格比对（缺失的显式登记，越权永远不吸收） ─────────
    release_surface = set()
    for spec in windows_policy.values():
        release_surface.update(spec.get("allowedCommands") or [])
    missing_impl_actual = sorted(release_surface - set(registered))
    missing_grants_actual: dict[str, list[str]] = {}
    for pattern, spec in sorted(windows_policy.items()):
        if pattern not in comparison:
            continue
        actual_commands = set(comparison[pattern]["actualCommands"])
        missing = set(spec.get("allowedCommands") or []) - actual_commands - set(missing_impl_actual)
        missing = {command for command in missing if command in registered}
        if missing:
            missing_grants_actual[pattern] = sorted(missing)
    declared_grants = {pattern: sorted((spec or {}).get("commands") or [])
                       for pattern, spec in (gap.get("pendingWindowGrants") or {}).items()}
    declared_impl = sorted(pending_impl)
    ledger_ok = declared_impl == missing_impl_actual
    case("caps::gap-ledger-pending-implementation", ledger_ok,
         {"declared": declared_impl, "actual": missing_impl_actual,
          "onlyDeclared": sorted(set(declared_impl) - set(missing_impl_actual)),
          "onlyActual": sorted(set(missing_impl_actual) - set(declared_impl))})
    grants_ok = declared_grants == missing_grants_actual
    case("caps::gap-ledger-pending-window-grants", grants_ok,
         {"declared": declared_grants, "actual": missing_grants_actual})
    gaps_remaining = len(missing_impl_actual) + sum(len(v) for v in missing_grants_actual.values())

    # ── protectedCommands 自洽 ───────────────────────────────────────
    protected_errors = []
    for command, spec in (policy.get("protectedCommands") or {}).items():
        declared_windows = set(spec.get("windows") or [])
        actual_windows = {pattern for pattern, value in comparison.items()
                          if command in value["allowedCommands"]}
        if declared_windows != actual_windows:
            protected_errors.append({"command": command,
                                     "declaredWindows": sorted(declared_windows),
                                     "policyWindows": sorted(actual_windows)})
    case("caps::protected-commands-window-scoped", not protected_errors, protected_errors)

    # ── release 排除面 / dev-only 命令 ───────────────────────────────
    release_denied = set(policy.get("releaseDeniedCommands") or [])
    release_granted = set()
    for value in release_expanded.values():
        release_granted.update(value["commands"])
    release_denied_hits = sorted(release_granted & release_denied)
    case("caps::release-denied-commands-not-granted", not release_denied_hits,
         {"hits": release_denied_hits, "devOnly": sorted(dev_commands),
          "note": "debug 命令只允许出现在 devOnlyCapabilities 排除的 capability 中"})
    debug_registered = parse_debug_invoke_commands()
    case("caps::debug-commands-declared-dev-only",
         set(debug_registered) <= set(policy.get("devOnlyCommands") or []),
         {"debugInvokeCommands": debug_registered,
          "declaredDevOnly": policy.get("devOnlyCommands")})

    # ── deferred / dropped / forbidden ───────────────────────────────
    deferred = set()
    for group in (policy.get("deferredCommands") or {}).values():
        deferred.update(group.get("commands") or [])
    deferred_hits = sorted(deferred & release_surface)
    case("caps::deferred-commands-not-granted", not deferred_hits,
         {"deferred": sorted(deferred), "granted": deferred_hits})
    dropped = set((policy.get("droppedCommands") or {}).keys())
    dropped_registered = sorted(dropped & set(registered))
    case("caps::dropped-commands-not-registered", not dropped_registered, dropped_registered)
    forbidden_patterns = policy.get("forbiddenCommandPatterns") or []
    forbidden_names = set(policy.get("forbiddenCommands") or [])
    forbidden_hits = []
    for command in sorted(set(registered) | set(permission_allow_commands) |
                          {c for spec in windows_policy.values()
                           for c in (spec.get("allowedCommands") or [])}):
        if command in forbidden_names or any(re.search(p, command) for p in forbidden_patterns):
            forbidden_hits.append(command)
    case("caps::forbidden-commands-absent", not forbidden_hits, forbidden_hits)

    # ── A12 静态半边 ────────────────────────────────────────────────
    cargo = read(TAURI / "Cargo.toml")
    wdio_optional = bool(re.search(
        r"tauri-plugin-wdio-webdriver\s*=\s*\{[^}]*optional\s*=\s*true", cargo))
    wdio_feature = "e2e-test = [\"dep:tauri-plugin-wdio-webdriver\"]" in cargo
    case("caps::wdio-feature-gated", wdio_optional and wdio_feature,
         {"optional": wdio_optional, "featureGate": wdio_feature})
    baseline = policy.get("securityBaseline") or {}
    devtools = baseline.get("devtools") or {}
    tauri_dep = re.search(r"^tauri\s*=\s*\{([^}]*)\}", cargo, re.M)
    tauri_features = re.findall(r'"([a-z0-9\-]+)"', tauri_dep.group(1)) if tauri_dep else []
    forbidden_features = [f for f in (devtools.get("cargoFeaturesForbidden") or [])
                          if f in tauri_features]
    case("caps::tauri-crate-no-devtools-feature", not forbidden_features,
         {"tauriFeatures": tauri_features, "forbiddenEnabled": forbidden_features})
    source_hits = []
    for path in sorted((TAURI / "src").glob("**/*.rs")):
        body = strip_rust_cfg_test(strip_rust_comments(read(path)))
        for pattern in devtools.get("sourceForbiddenPatterns") or []:
            if pattern in body:
                source_hits.append({"file": str(path.relative_to(ROOT)), "pattern": pattern})
    case("caps::no-devtools-control-in-source", not source_hits, source_hits)

    release_conf_text = read(TAURI / "tauri.release.conf.json")
    case("caps::release-config-has-no-dev-url",
         bool(release_conf_text) and "devUrl" not in release_conf_text,
         {"releaseConfigPresent": bool(release_conf_text)})
    release_conf = json.loads(release_conf_text) if release_conf_text else {}
    expected_global_tauri = (baseline.get("releaseConfig") or {}).get("withGlobalTauri")
    actual_global_tauri = ((release_conf.get("app") or {}).get("withGlobalTauri"))
    case("caps::with-global-tauri-matches-policy", actual_global_tauri == expected_global_tauri,
         {"actual": actual_global_tauri, "policy": expected_global_tauri,
          "note": "withGlobalTauri 只暴露 ACL 允许的命令，不是 ACL 绕过；T06 R09 保留 true 以复用同一 React 产物"})
    dev_url_hits = []
    for path in sorted(TAURI.rglob("*")):
        if not path.is_file() or path.suffix not in (".json", ".rs", ".toml"):
            continue
        if "target" in path.parts or "gen" in path.parts:
            continue
        if path.name == "tauri.dev.conf.json":
            continue
        body = read(path)
        if path.suffix == ".rs":
            body = strip_rust_cfg_test(strip_rust_comments(body))
        if "5173" in body:
            dev_url_hits.append(str(path.relative_to(ROOT)))
    case("caps::no-dev-port-in-production-config", not dev_url_hits, dev_url_hits)

    # ── D11：test hooks feature 门控（交付 release 不含测试注入点） ──
    test_control = policy.get("testControl") or {}
    hooks_feature = test_control.get("feature") or "r09-test-hooks"
    feature_declared = bool(re.search(
        rf"^{re.escape(hooks_feature)}\s*=\s*\[", cargo, re.M))
    case("caps::test-hooks-feature-declared", feature_declared,
         {"feature": hooks_feature, "note": "测试注入点必须由该 Cargo feature 编译门控"})

    receipt_path = TAURI / ".tauri-build" / "build-receipt-release.json"
    receipt = None
    if receipt_path.is_file():
        try:
            receipt = json.loads(read(receipt_path))
        except json.JSONDecodeError:
            receipt = None
    receipt_features = list(((receipt or {}).get("inputs") or {}).get("features") or [])
    if receipt is not None:
        evidence_build = (receipt.get("evidenceBuild")
                          if "evidenceBuild" in receipt
                          else hooks_feature in receipt_features)
    else:
        evidence_build = None
    if receipt is None:
        case("caps::delivery-release-excludes-test-hooks", False,
             {"receipt": str(receipt_path.relative_to(ROOT)) if receipt_path.is_file() else "missing",
              "note": "缺少交付 release 构建回执；请跑 --release 构建（--features r09-host）"})
    elif evidence_build:
        case("caps::delivery-release-excludes-test-hooks", False,
             {"receipt": str(receipt_path.relative_to(ROOT)),
              "evidenceBuild": evidence_build, "features": receipt_features,
              "pending": "PENDING_DELIVERY_BUILD",
              "note": "该回执是 evidence build（含 r09-test-hooks），不得当作交付 release；需另跑一次交付 release 构建"})
    else:
        hooks_present = hooks_feature in receipt_features
        case("caps::delivery-release-excludes-test-hooks", not hooks_present,
             {"receipt": str(receipt_path.relative_to(ROOT)),
              "evidenceBuild": evidence_build, "features": receipt_features,
              "forbiddenFeature": hooks_feature if hooks_present else None})

    # 交付 release 二进制不得含测试注入 env/符号（证据构建不作为该检查对象）。
    release_binary = ((receipt or {}).get("artifacts") or {}).get("executable")
    reject_tokens = list(test_control.get("releaseMustReject") or []) + \
        list(test_control.get("releaseMustRejectSymbols") or [])
    if not release_binary or not Path(release_binary).is_file() or receipt is None or evidence_build:
        case("caps::delivery-release-binary-no-test-env", False,
             {"binary": release_binary, "receipt": str(receipt_path.relative_to(ROOT)),
              "note": "缺少交付 release 二进制/回执，或回执为 evidence build（不得作为交付检查对象）"})
    else:
        data = Path(release_binary).read_bytes()
        hits = []
        for token in reject_tokens:
            count = data.count(token.encode())
            if count:
                hits.append({"token": token, "count": count})
        case("caps::delivery-release-binary-no-test-env", not hits,
             {"binary": release_binary, "hits": hits,
              "note": "交付 release 二进制不得含测试注入 env 名/调试符号（A12）"})

    # asset protocol 属 D8/T03-T05 接线面（不是 A11/A12 门）：仅在配置已出现时
    # 检查其 scope 不得出现整机放行；未接线由 PROGRESS 的 D8 缺口跟踪，不在本审计
    # ── asset protocol（v2 Patch §1）：静态 scope 收敛 + 运行时授权由 host.rs 负责 ──
    # 允许的静态 scope 前缀（$HOME 下三个标准 LINGXI_HOME + $TEMP）；其余形态
    # （尤其 "/**"、""、$HOME/**）一律红。运行时 allow_directory 的验证逻辑在
    # host.rs::validate_asset_workspace_root 单测覆盖（越界路径拒绝）。
    allowed_scope_entries = {
        "$HOME/.lingxi/**", "$HOME/.lingxi-dev/**", "$HOME/.hanako-dev/**", "$TEMP/**",
    }
    scope_reports = {}
    scope_violations = []
    for name, config in (("tauri.conf.json", json.loads(read(TAURI / "tauri.conf.json")) if (TAURI / "tauri.conf.json").is_file() else {}),
                         ("tauri.release.conf.json", release_conf),
                         ("tauri.dev.conf.json", json.loads(read(TAURI / "tauri.dev.conf.json")) if (TAURI / "tauri.dev.conf.json").is_file() else {})):
        asset = (((config.get("app") or {}).get("security") or {}).get("assetProtocol"))
        scope = (asset or {}).get("scope") or []
        scope_reports[name] = {"present": asset is not None,
                               "enable": (asset or {}).get("enable"),
                               "scope": scope}
        if asset is None:
            scope_violations.append({"config": name, "reason": "assetProtocol 缺失"})
            continue
        if not (asset or {}).get("enable"):
            scope_violations.append({"config": name, "reason": "assetProtocol.enable != true"})
        if not scope:
            scope_violations.append({"config": name, "reason": "scope 为空（getFileUrl 会被拒绝）"})
        for entry in scope:
            if entry not in allowed_scope_entries:
                scope_violations.append({"config": name, "reason": "scope 越界/过宽",
                                         "entry": entry})
    case("caps::asset-protocol-scope-confined", not scope_violations,
         {"configs": scope_reports, "violations": scope_violations,
          "allowedEntries": sorted(allowed_scope_entries),
          "note": "静态 scope 仅标准 LINGXI_HOME/$TEMP；实际 home 与 home 外 workspace 运行时 add（host.rs 单测校验越界拒绝）"})

    base_conf_text = read(TAURI / "tauri.conf.json")
    base_conf = json.loads(base_conf_text) if base_conf_text else {}
    base_csp = (((base_conf.get("app") or {}).get("security") or {}).get("csp") or "")
    base_directives = parse_csp(base_csp)
    base_csp_ok = ({"asset:", "http://asset.localhost"} <= set(base_directives.get("img-src") or [])
                   and {"asset:", "http://asset.localhost"} <= set(base_directives.get("media-src") or []))
    case("caps::base-config-csp-asset", base_csp_ok,
         {"imgSrc": base_directives.get("img-src"),
          "mediaSrc": base_directives.get("media-src"),
          "note": "基础配置（dev/合并前）也必须允许 asset，否则 getFileUrl/img 预览被 CSP 拒"})
    # H1 file-url-asset 根因回归：页面级 meta CSP（connection-csp.js）必须允许
    # Tauri asset 协议；否则 Two-CSP 交集会拦截 convertFileSrc() 的图片/媒体。
    meta_csp_reports = []
    meta_csp_ok = True
    for path in (Path("desktop/src/modules/connection-csp.js"),
                 Path("desktop/dist-renderer/modules/connection-csp.js")):
        if not path.is_file():
            continue
        text = read(path)
        img_ok = re.search(r'"img-src"\s*:\s*\[([^\]]*)\]', text)
        media_ok = re.search(r'"media-src"\s*:\s*\[([^\]]*)\]', text)
        img_tokens = img_ok.group(1) if img_ok else ""
        media_tokens = media_ok.group(1) if media_ok else ""
        ok = ("asset:" in img_tokens and "http://asset.localhost" in img_tokens
              and "asset:" in media_tokens and "http://asset.localhost" in media_tokens)
        meta_csp_reports.append({"file": str(path), "imgSrc": img_tokens.strip()[:400],
                                 "mediaSrc": media_tokens.strip()[:400], "ok": ok})
        meta_csp_ok = meta_csp_ok and ok
    if meta_csp_reports:
        case("caps::page-meta-csp-allows-asset", meta_csp_ok, meta_csp_reports)
    base_window_devtools = [
        {"label": window.get("label"), "devtools": window.get("devtools")}
        for window in ((base_conf.get("app") or {}).get("windows") or [])
        if window.get("devtools") is True
    ]
    case("caps::base-window-devtools-disabled", not base_window_devtools,
         {"windowsWithDevtools": base_window_devtools,
          "note": "v2 Patch §2：release 不得有 devtools 右键/菜单入口；基础窗口显式 devtools=false"})

    # ── 汇总 ────────────────────────────────────────────────────────
    failed = [row["case"] for row in CASES if not row["ok"]]
    if failed:
        status, exit_code = "FAIL", 2
    elif gaps_remaining > 0:
        status, exit_code = "PENDING_GAPS", 4
    else:
        status, exit_code = "PASS", 0
    extra = {
        "policy": rel(policy_path),
        "windowComparison": comparison,
        "gapLedger": {
            "declaredPendingImplementation": declared_impl,
            "actualPendingImplementation": missing_impl_actual,
            "declaredPendingWindowGrants": declared_grants,
            "actualPendingWindowGrants": missing_grants_actual,
            "remaining": gaps_remaining,
            "closeoutRule": "T06 A11 静态收口要求 remaining == 0（运行期负向矩阵另计）",
        },
        "releaseDeniedExposure": release_denied_hits,
        "dangerousPluginLeaves": dangerous_any,
        "devOnly": {"presentCapabilities": present_dev, "declared": sorted(dev_commands)},
    }
    return finish(evidence, status, exit_code, started, registered, manifest,
                  capabilities, permission_allow_commands, release_expanded, policy, extra,
                  window_comparison=comparison)


def finish(evidence, status, exit_code, started, registered, manifest, capabilities,
           permission_allow_commands, expanded, policy, extra,
           window_comparison=None) -> int:
    failed = [row["case"] for row in CASES if not row["ok"]]
    result = {
        "schema": "lingxi.r09.capability-audit.v1",
        "suite": "r09_capability_audit",
        "status": status,
        "exitCode": exit_code,
        "registeredCommands": registered,
        "manifestCommands": manifest,
        "capabilities": {k: v["windows"] for k, v in capabilities.items()},
        "permissionCommands": permission_allow_commands,
        "expandedPerWindow": {label: expanded[label] for label in sorted(expanded)},
        "cases": CASES,
        "failedCases": failed,
        "policy": str(policy) if isinstance(policy, str) else (
            extra.get("policy") if policy else None),
        "durationSecs": round(time.time() - started, 3),
    }
    result.update(extra)
    if evidence is not None:
        (evidence / "capability-audit.json").write_text(
            json.dumps(result, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        (evidence / "cases.json").write_text(json.dumps(
            {"schema": "lingxi.leaf-case-results.v1", "suite": "r09_capability_audit",
             "cases": CASES}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        (evidence / "output.log").write_text("\n".join(LOGS) + "\n", encoding="utf-8")
        (evidence / "result.json").write_text(json.dumps({
            "schema": "lingxi.r09.suite-receipt.v1", "suite": "r09_capability_audit",
            "status": status, "exitCode": exit_code, "caseCount": len(CASES),
            "failedCases": failed, "audit": "capability-audit.json",
            "policy": result.get("policy"),
            "gapLedgerRemaining": (result.get("gapLedger") or {}).get("remaining"),
        }, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"r09_capability_audit: status={status} cases={len(CASES)} failed={failed} "
          f"gaps={(result.get('gapLedger') or {}).get('remaining')}")
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
