#!/usr/bin/env python3
"""R09 T06 静态能力审计：命令注册面 ↔ ACL 权限 ↔ capability 展开 ↔ 意图策略。

R09-A11/A12 的静态半边（运行期逐窗口负向 invoke 由 GUI 解禁后的 E2E 提供）：
  1. `lib.rs` 的 `invoke_handler(generate_handler![...])` 命令集合；
  2. `build.rs` 的 `AppManifest::commands([...])` 命令集合 —— 两者必须一致；
  3. `permissions/autogenerated/*.toml` 的 permission → commands 映射（取 allow 侧）；
  4. `capabilities/*.json` 的 window label 模式 → 自定义权限 + 插件权限；
  5. 按窗口求 capability 并集（多 capability 叠加不扩权）：与
     `docs/rust-tauri/R09/R09_COMMAND_POLICY.json`（意图白名单）比较：
       - 越权集合（actual - allowed）**一律报红**，策略绝不吸收当前配置；
       - 缺失集合必须与 policy.gapLedger 登记的缺口逐条相等（缺口的显式账本，
         不允许静默消失；T06 收口时账本必须为空）；
       - 插件权限只允许 policy 基线（core:event:default），并用
         gen/schemas/acl-manifests.json 展开聚合权限，命中危险 leaf 即红
         （例如 core:default 会展开出 core:tray:*/core:menu:*/devtools 权限）；
       - windows 键必须与 `src/native/window_labels.rs` 的窗口角色逐字一致；
       - protectedCommands 的窗口集合必须与白名单自洽；
       - releaseDeniedCommands 不得出现在 release 展开中；
  6. A12 静态半边：wdio 插件必须 feature-gated；release config 不得有 devUrl/
     dev 端口；tauri crate 不得启用 devtools feature；源码不得含 devtools 控制
     面；测试 env 注入点不得在非 debug 路径生效。

退出码：
  0  = PASS（无越权、缺口账本为空、A12 静态全绿）
  2  = FAIL（存在越权/未登记缺口/A12 违规/策略缺失但已有静态违规）
  3  = PENDING_POLICY（策略文件缺失**且**无其它静态违规；不冒充 PASS）
  4  = PENDING_GAPS（无违规，但 policy.gapLedger 仍非空 = T06 静态面未收口）

用法：
  python3 -B scripts/rust-tauri/r09_capability_audit.py --evidence <dir>
  python3 -B scripts/rust-tauri/r09_capability_audit.py --evidence <dir> --policy docs/rust-tauri/R09/R09_COMMAND_POLICY.json
"""

