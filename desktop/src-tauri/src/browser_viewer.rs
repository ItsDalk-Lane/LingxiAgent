/// 宿主唯一持有的连接凭据。故意不实现 `Serialize`/`Debug`：token 只能留在
/// 宿主 state 内，任何命令/事件/日志都不得带出。
#[derive(Clone)]
struct HostConnection {
    identity: String,
    key: String,
    base_url: String,
    token: Option<String>,
    server_id: String,
    label: Option<String>,
}

