/// 宿主 state：唯一连接 + 当前 viewer target。两者用不同锁，避免网络请求
/// 期间持锁；任何 await 之后都必须重新校验 identity。
#[derive(Default)]
pub struct BrowserViewerState {
    connection: Mutex<Option<HostConnection>>,
    viewer_target: Mutex<Option<BrowserViewerTarget>>,
}

// ── 纯校验/熵辅助（不依赖窗口，便于单测） ──────────────────────────────────

/// OS CSPRNG：`getentropy(2)` 取 32 字节（macOS/Linux）。非 Unix 平台 fail
/// closed（返回 `browser_entropy_unavailable`，不降级成时间戳/哈希伪随机）；
/// Windows/Linux-x64 平台接线前必须由 T06 决定获批的 CSPRNG 依赖。
fn csprng_32() -> Result<[u8; 32], String> {
    let mut bytes = [0u8; 32];
    #[cfg(unix)]
    {
        // SAFETY: 缓冲区为 32 字节可写内存，长度 ≤ getentropy 的 256 上限；
        // 失败（-1）时显式返回错误，不使用未初始化/部分填充的数据。
        let code =
            unsafe { libc::getentropy(bytes.as_mut_ptr().cast::<libc::c_void>(), bytes.len()) };
        if code != 0 {
            return Err("browser_entropy_unavailable".into());
        }
        Ok(bytes)
    }
    #[cfg(not(unix))]
    {
        let _ = &mut bytes;
        Err("browser_entropy_unavailable".into())
    }
}

fn hex_32(bytes: [u8; 32]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// 不透明 connectionKey：CSPRNG 32B → 64 hex。viewer 只能拿它换命令，不能
/// 反推 baseUrl/token（token 从不进入 viewer）。
fn connection_key() -> Result<String, String> {
    csprng_32().map(hex_32)
}

/// 服务会话路径的**唯一**合法形态：`native:<session-id>`（服务
/// `session_locator::native`）。绝对文件路径形态被显式拒绝——renderer 不能
/// 通过 sessionPath 指定本机任意文件；若未来支持 legacy JSONL 绝对路径，
/// 必须先 canonicalize 并证明位于本机 `LINGXI_HOME` 会话域内（见模块注释）。
fn native_session(value: &str) -> Result<(), String> {
    let Some(rest) = value.strip_prefix("native:") else {
        return Err("browser_native_session_required".into());
    };
    if rest.is_empty()
        || rest.chars().count() > 256
        || rest
            .chars()
            .any(|c| c.is_whitespace() || matches!(c, '/' | '?' | '#') || c.is_control())
    {
        return Err("browser_native_session_required".into());
    }
    Ok(())
}

fn valid_base_url(value: &str) -> Result<String, String> {
    let parsed = reqwest::Url::parse(value).map_err(|_| "browser_connection_invalid")?;
    if !matches!(parsed.scheme(), "http" | "https")
        || !parsed.username().is_empty()
        || parsed.password().is_some()
        || parsed.query().is_some()
        || parsed.fragment().is_some()
    {
        return Err("browser_connection_invalid".into());
    }
    Ok(value.trim_end_matches('/').to_string())
}

fn valid_action(value: &str) -> Result<(), String> {
    if VIEWER_ACTIONS.contains(&value) {
        Ok(())
    } else {
        Err("browser_action_invalid".into())
    }
}

fn valid_tab_id(value: &str) -> Result<(), String> {
    if value.is_empty()
        || value.len() > 4096
        || value
            .chars()
            .any(|c| c.is_whitespace() || matches!(c, '*' | '?') || c.is_control())
    {
        return Err("browser_tab_invalid".into());
    }
    Ok(())
}

/// 导航/新开标签的 URL：只允许 http/https 且无 userinfo（严格解析，拒绝
/// `javascript:`/`file:`/`data:` 与 `http://user:pass@…`）。
fn valid_request_url(value: &str) -> Result<(), String> {
    if value.len() > 8192 {
        return Err("browser_url_invalid".into());
    }
    let parsed = reqwest::Url::parse(value).map_err(|_| "browser_url_invalid")?;
    if !matches!(parsed.scheme(), "http" | "https")
        || !parsed.username().is_empty()
        || parsed.password().is_some()
    {
        return Err("browser_url_invalid".into());
    }
    Ok(())
}

fn connection_identity(input: &BrowserConnectionInput) -> String {
    // 与 rust-browser-control.cjs `connectionIdentity` 同字段集合；只用于
    // 判断连接是否变化，不得写入日志或证据（token 在此整体哈希）。
    use sha2::Digest as _;
    let fields = [
        Some(input.connection_id.as_str()),
        input.kind.as_deref(),
        Some(input.base_url.as_str()),
        input.token.as_deref(),
        Some(input.server_id.as_str()),
        input.server_node_id.as_deref(),
        input.server_node_kind.as_deref(),
        input.server_node_transport.as_deref(),
        input.user_id.as_deref(),
        input.studio_id.as_deref(),
        input.auth_state.as_deref(),
        input.trust_state.as_deref(),
        input.credential_kind.as_deref(),
    ];
    let mut hasher = sha2::Sha256::new();
    for field in fields {
        hasher.update(field.unwrap_or("").as_bytes());
        hasher.update(b"\0");
    }
    hasher
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn is_main(window: &WebviewWindow) -> bool {
    window.label() == MAIN_LABEL
}

fn is_viewer(window: &WebviewWindow) -> bool {
    window.label() == VIEWER_LABEL
}

/// 销毁旧 viewer。关闭失败不能留下两个 viewer：Tauri `close` 是 close-request
/// 语义，因此直接 `destroy`；这里从不调用浏览器 stop/revoke。
fn destroy_viewer(app: &AppHandle) {
    if let Some(existing) = app.get_webview_window(VIEWER_LABEL) {
        let _ = existing.destroy();
    }
}

fn connection_snapshot(state: &BrowserViewerState) -> Option<(String, String, Option<String>)> {
    state.connection.lock().ok()?.as_ref().map(|current| {
        (
            current.key.clone(),
            current.base_url.clone(),
            current.token.clone(),
        )
    })
}

// ── 命令：登记/清空连接（main only） ────────────────────────────────────────

/// main 窗口登记当前服务连接；返回 viewer 可用的不透明 connectionKey。
/// `None` 表示断开：清空连接 + viewer target、销毁 viewer，并通知 renderer。
///
/// 权限：仅 `main` 窗口；其他窗口 `browser_sender_denied`。
#[tauri::command]
pub fn set_browser_connection(
    window: WebviewWindow,
    app: AppHandle,
    state: State<'_, BrowserViewerState>,
    connection: Option<BrowserConnectionInput>,
) -> Result<Option<String>, String> {
    if !is_main(&window) {
        return Err("browser_sender_denied".into());
    }
    let Some(input) = connection else {
        let had = state
            .connection
            .lock()
            .map_err(|_| "browser_state_unavailable")?
            .take()
            .is_some();
        *state
            .viewer_target
            .lock()
            .map_err(|_| "browser_state_unavailable")? = None;
        destroy_viewer(&app);
        if had {
            let _ = app.emit(CONNECTION_CHANGED_EVENT, json!({"active": false}));
        }
        return Ok(None);
    };
    if input.server_node_kind.as_deref() != Some("lingxi-service") {
        return Err("browser_connection_invalid".into());
    }
    if input.connection_id.is_empty() || input.server_id.is_empty() {
        return Err("browser_connection_invalid".into());
    }
    if let Some(token) = input.token.as_deref() {
        if token.contains(['\r', '\n']) {
            return Err("browser_connection_invalid".into());
        }
    }
    let base_url = valid_base_url(&input.base_url)?;
    let identity = connection_identity(&input);
    let mut connection = state
        .connection
        .lock()
        .map_err(|_| "browser_state_unavailable")?;
    if connection
        .as_ref()
        .is_some_and(|current| current.identity == identity)
    {
        return Ok(connection.as_ref().map(|current| current.key.clone()));
    }
    let key = connection_key()?;
    *connection = Some(HostConnection {
        identity,
        key: key.clone(),
        base_url,
        token: input.token.clone(),
        server_id: input.server_id.clone(),
        label: input.label.clone(),
    });
    // 连接身份变化：旧 viewer 上下文必然失效，先销毁旧窗口再允许重开。
    drop(connection);
    *state
        .viewer_target
        .lock()
        .map_err(|_| "browser_state_unavailable")? = None;
    destroy_viewer(&app);
    let _ = app.emit(
        CONNECTION_CHANGED_EVENT,
        json!({"active": true, "reason": "connection-changed"}),
    );
    Ok(Some(key))
}

/// 仅 browser-viewer 窗口可读自己的不透明上下文；其他窗口（含 main）返回 null。
#[tauri::command]
pub fn get_browser_viewer_context(
    app: AppHandle,
    window: WebviewWindow,
    state: State<'_, BrowserViewerState>,
) -> Result<Option<BrowserViewerContext>, String> {
    if !is_viewer(&window) {
        return Ok(None);
    }
    // 没有登记窗口或连接已断时，不能回放旧 target。
    if app.get_webview_window(VIEWER_LABEL).is_none() {
        return Ok(None);
    }
    let Some(target) = state
        .viewer_target
        .lock()
        .map_err(|_| "browser_state_unavailable")?
        .clone()
    else {
        return Ok(None);
    };
    let Some(connection) = state
        .connection
        .lock()
        .map_err(|_| "browser_state_unavailable")?
        .as_ref()
        .cloned()
    else {
        return Ok(None);
    };
    if connection.key != target.connection_key {
        return Ok(None);
    }
    Ok(Some(BrowserViewerContext {
        connection_key: connection.key,
        session_path: target.session_path,
        // 与 Electron `get-browser-viewer-context` 同语义：
        // executionNode=connection.serverId，serviceLabel=label||serverId。
        execution_node: connection.server_id.clone(),
        service_label: connection
            .label
            .clone()
            .unwrap_or_else(|| connection.server_id),
        service_url: connection.base_url,
    }))
}

// ── 命令：打开/关闭 viewer ─────────────────────────────────────────────────

/// main only：校验不透明 target 后销毁旧 viewer、记录 target、创建控制面板窗口。
/// 打开窗口本身既不建标签也不启动浏览器（与 Electron 语义一致）。
///
/// 权限：仅 `main` 窗口；其他窗口 `browser_sender_denied`。
#[tauri::command]
pub fn open_browser_viewer(
    window: WebviewWindow,
    app: AppHandle,
    state: State<'_, BrowserViewerState>,
    target: BrowserViewerTarget,
) -> Result<BrowserViewerOpenReply, String> {
    if !is_main(&window) {
        return Err("browser_sender_denied".into());
    }
    let Some((key, _base_url, _token)) = connection_snapshot(&state) else {
        return Err("browser_connection_required".into());
    };
    if target.connection_key != key {
        return Err("browser_connection_changed".into());
    }
    native_session(&target.session_path)?;
    destroy_viewer(&app);
    *state
        .viewer_target
        .lock()
        .map_err(|_| "browser_state_unavailable")? = Some(target);
    WebviewWindowBuilder::new(&app, VIEWER_LABEL, WebviewUrl::App(VIEWER_URL.into()))
        .title("Lingxi Browser")
        .inner_size(1100.0, 760.0)
        .min_inner_size(620.0, 420.0)
        .build()
        .map_err(|error| format!("browser_viewer_window_failed: {error}"))?;
    Ok(BrowserViewerOpenReply { opened: true })
}

/// viewer 关闭自己；main 关闭 viewer。两者都只销毁窗口/清 target，
/// **绝不**发 stop/revoke（急停只能是显式 `rust_browser_request(..., "stop")`）。
#[tauri::command]
pub fn close_browser_viewer(
    window: WebviewWindow,
    app: AppHandle,
    state: State<'_, BrowserViewerState>,
) -> Result<(), String> {
    if is_viewer(&window) {
        *state
            .viewer_target
            .lock()
            .map_err(|_| "browser_state_unavailable")? = None;
        return window.close().map_err(|error| error.to_string());
    }
    if is_main(&window) {
        *state
            .viewer_target
            .lock()
            .map_err(|_| "browser_state_unavailable")? = None;
        destroy_viewer(&app);
        return Ok(());
    }
    Err("browser_sender_denied".into())
}

// ── 命令：浏览器控制请求（main 或当前 viewer） ─────────────────────────────

/// 宿主代为发出服务 HTTP，凭据不进 viewer。
///
/// - main：可指定任意合法 target（connectionKey 必须等于当前连接）。
/// - viewer：`target.sessionPath`/`target.connectionKey` 必须等于打开本窗口时
///   登记的 target，否则显式拒绝（不接受另一会话/另一连接）。
/// - `action` 只能是 [`VIEWER_ACTIONS`]；`options.tabId`/`options.url` 按白名单
///   校验（url 只允许 http/https 且无 userinfo）。
/// - 返回服务 JSON 原文；服务错误/非 2xx 统一以服务 error 字符串或
///   `browser_request_failed:<status>` 返回，调用方按词表展示。
#[tauri::command]
pub async fn rust_browser_request(
    window: WebviewWindow,
    state: State<'_, BrowserViewerState>,
    target: BrowserViewerTarget,
    action: String,
    options: Option<BrowserRequestOptions>,
) -> Result<Value, String> {
    let caller_viewer = is_viewer(&window);
    if !caller_viewer && !is_main(&window) {
        return Err("browser_sender_denied".into());
    }
    valid_action(&action)?;
    native_session(&target.session_path)?;
    if caller_viewer {
        // viewer 只能操作打开自己的那个 target；跨会话/跨连接一律拒绝。
        let stored = state
            .viewer_target
            .lock()
            .map_err(|_| "browser_state_unavailable")?
            .clone()
            .ok_or("browser_session_changed")?;
        if stored.session_path != target.session_path {
            return Err("browser_session_changed".into());
        }
        if stored.connection_key != target.connection_key {
            return Err("browser_connection_changed".into());
        }
    }
    let options = options.unwrap_or(BrowserRequestOptions {
        tab_id: None,
        url: None,
    });
    if let Some(tab_id) = options.tab_id.as_deref() {
        valid_tab_id(tab_id)?;
    }
    if let Some(url) = options.url.as_deref() {
        valid_request_url(url)?;
    }
    if options.tab_id.is_some() && !matches!(action.as_str(), "switch_tab" | "close_tab") {
        return Err("browser_tab_invalid".into());
    }
    if options.url.is_some() && !matches!(action.as_str(), "new_tab" | "open") {
        return Err("browser_url_invalid".into());
    }
    let Some((key, base_url, token)) = connection_snapshot(&state) else {
        return Err("browser_connection_required".into());
    };
    if target.connection_key != key {
        return Err("browser_connection_changed".into());
    }
    let path = match action.as_str() {
        "workspaces" => "workspaces",
        "stop" => "close-session",
        "open" => "open-session",
        _ => "command",
    };
    let method = if action == "workspaces" {
        reqwest::Method::GET
    } else {
        reqwest::Method::POST
    };
    let body = match action.as_str() {
        "workspaces" => None,
        "stop" => Some(json!({"sessionPath": target.session_path, "revoke": true})),
        "open" => Some(json!({"sessionPath": target.session_path})),
        _ => Some(json!({
            "sessionPath": target.session_path,
            "action": action,
            "tabId": options.tab_id,
            "url": options.url,
        })),
    };
    let client = reqwest::Client::builder()
        .timeout(REQUEST_TIMEOUT)
        .redirect(reqwest::redirect::Policy::none())
        .build()
        .map_err(|_| "browser_client_unavailable".to_string())?;
    let mut request = client.request(method, format!("{base_url}/lingxi/v1/browser/{path}"));
    if let Some(token) = token {
        request = request.bearer_auth(token);
    }
    if let Some(body) = body {
        request = request.json(&body);
    }
    let response = request
        .send()
        .await
        .map_err(|_| "browser_request_unreachable".to_string())?;
    let status = response.status();
    let data: Value = response
        .json()
        .await
        .map_err(|_| "browser_response_invalid".to_string())?;
    // await 期间连接可能被替换/断开：迟到结果不能作用到新连接。
    let still_current = state
        .connection
        .lock()
        .map_err(|_| "browser_state_unavailable")?
        .as_ref()
        .is_some_and(|current| current.key == key);
    if !still_current {
        return Err("browser_connection_changed".into());
    }
    if !status.is_success() {
        if let Some(message) = data.get("error").and_then(Value::as_str) {
            return Err(message.to_string());
        }
        return Err(format!("browser_request_failed:{}", status.as_u16()));
    }
    if let Some(message) = data.get("error").and_then(Value::as_str) {
        return Err(message.to_string());
    }
    if !data.is_object() {
        return Err("browser_response_invalid".into());
    }
    Ok(data)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn native_session_matches_service_contract_and_rejects_paths() {
        assert!(native_session("native:session-1").is_ok());
        assert!(native_session("native:").is_err());
        assert!(native_session("session-1").is_err());
        // 文件系统路径形态被拒绝：renderer 不能借 sessionPath 指定本机文件。
        assert!(native_session("/Users/example/.lingxi/sessions/x.jsonl").is_err());
        assert!(native_session("../etc/passwd").is_err());
        assert!(native_session("native:a b").is_err());
        assert!(native_session("native:a/b").is_err());
        assert!(native_session(&format!("native:{}", "x".repeat(257))).is_err());
    }

    #[test]
    fn base_url_rejects_credentials_query_and_foreign_scheme() {
        assert_eq!(
            valid_base_url("http://127.0.0.1:1234/").unwrap(),
            "http://127.0.0.1:1234"
        );
        assert!(valid_base_url("file:///tmp/x").is_err());
        assert!(valid_base_url("http://user:pass@127.0.0.1:1").is_err());
        assert!(valid_base_url("http://127.0.0.1:1/?x=1").is_err());
        assert!(valid_base_url("http://127.0.0.1:1/#f").is_err());
    }

    #[test]
    fn request_url_is_http_only_without_userinfo() {
        assert!(valid_request_url("https://example.test/x").is_ok());
        assert!(valid_request_url("http://127.0.0.1:1234/x").is_ok());
        assert!(valid_request_url("javascript:alert(1)").is_err());
        assert!(valid_request_url("file:///etc/passwd").is_err());
        assert!(valid_request_url("data:text/html,<script>").is_err());
        assert!(valid_request_url("http://user:pass@example.test/").is_err());
        assert!(valid_request_url(&format!("https://example.test/{}", "x".repeat(8192))).is_err());
    }

    #[test]
    fn actions_and_tabs_are_whitelisted() {
        for action in VIEWER_ACTIONS {
            assert!(valid_action(action).is_ok(), "{action}");
        }
        assert!(valid_action("eval").is_err());
        assert!(valid_action("Stop").is_err());
        assert!(valid_tab_id("tab-1").is_ok());
        assert!(valid_tab_id("").is_err());
        assert!(valid_tab_id("tab 1").is_err());
        assert!(valid_tab_id("tab*").is_err());
    }

    #[test]
    fn viewer_url_targets_the_real_renderer_entry() {
        // 真实入口是 vite 多入口 `browser-viewer`（desktop/src/browser-viewer.html）；
        // `BrowserViewerApp` 只认 mode==='native'。误用 main 的 index.html 会加载
        // 主界面而不是控制面板，必须由测试固定。
        assert_eq!(VIEWER_URL, "browser-viewer.html?mode=native");
        assert!(VIEWER_URL.contains("browser-viewer.html"));
        assert!(VIEWER_URL.contains("mode=native"));
    }

    #[test]
    fn viewer_context_shape_matches_react_type() {
        // 对照 `desktop/src/react/types.ts` 的 RustBrowserViewerContext 与
        // Electron main.cjs `get-browser-viewer-context` 返回结构：
        // {connectionKey, sessionPath, executionNode, serviceLabel, serviceUrl}。
        let context = BrowserViewerContext {
            connection_key: "0123456789abcdef".repeat(4),
            session_path: "native:s1".into(),
            execution_node: "node-1".into(),
            service_label: "Lingxi".into(),
            service_url: "http://127.0.0.1:62442".into(),
        };
        let value = serde_json::to_value(&context).expect("context serializes");
        let object = value.as_object().expect("object");
        let mut keys: Vec<&str> = object.keys().map(String::as_str).collect();
        keys.sort_unstable();
        assert_eq!(
            keys,
            [
                "connectionKey",
                "executionNode",
                "serviceLabel",
                "serviceUrl",
                "sessionPath"
            ]
        );
        // 绝不携带 token / 服务 bearer 等价物。
        for forbidden in ["token", "authorization", "bearer", "secret"] {
            assert!(!value.to_string().to_lowercase().contains(forbidden));
        }
        assert_eq!(object["sessionPath"], "native:s1");
        assert_eq!(object["executionNode"], "node-1");
    }

    #[test]
    fn connection_identity_changes_with_token_and_never_contains_it() {
        let base = BrowserConnectionInput {
            connection_id: "c1".into(),
            kind: None,
            base_url: "http://127.0.0.1:1".into(),
            token: Some("super-secret-token".into()),
            server_id: "s1".into(),
            server_node_kind: Some("lingxi-service".into()),
            server_node_id: None,
            server_node_transport: None,
            user_id: None,
            studio_id: None,
            auth_state: None,
            trust_state: None,
            credential_kind: None,
            label: None,
        };
        let first = connection_identity(&base);
        let mut changed = base.clone();
        changed.token = Some("other-token".into());
        assert_ne!(first, connection_identity(&changed));
        assert!(!first.contains("super-secret-token"));
        // connectionKey 是 CSPRNG 32B hex，且不含服务地址信息。
        let key = connection_key().expect("OS CSPRNG");
        assert_eq!(key.len(), 64);
        assert!(key.chars().all(|c| c.is_ascii_hexdigit()));
        assert_ne!(key, connection_key().expect("OS CSPRNG"));
        assert!(!key.contains("127.0.0.1"));
    }
}
