//! R09-T05：浏览器控制面板（browser-viewer）的 Tauri 宿主桥——**接口草案，未注册**。
//!
//! 设计依据：`docs/rust-tauri/R09/T05_BROWSER_PDF_DESIGN.md` §2.2/§2.5/§2.6、
//! `docs/rust-tauri/R01/ADR-002-browser-host.md`。受控网页**不在** Tauri webview 内：
//! 网页窗口属于 lingxi-service 启动的 Chromium 进程；本模块只负责
//! 「控制面板窗口 + 宿主内 HTTP 控制桥」。viewer webview 拿不到服务 bearer token，
//! 只拿不透明 `connectionKey` + `sessionPath`，所有 HTTP 由宿主 reqwest 发出。
//!
//! ## A11/T06 安全边界（实现与评审时不得弱化）
//! - `set_browser_connection`、`open_browser_viewer` **仅 main 窗口**可调
//!   （校验 `WebviewWindow::label() == "main"`）；其他窗口一律显式
//!   `browser_sender_denied`，不得静默 no-op。
//! - `get_browser_viewer_context` 仅 `browser-viewer` 窗口返回 `Some`；
//!   其他窗口返回 `None`（不泄露连接/target 状态）。
//! - `rust_browser_request`：viewer 调用时 `sessionPath` 必须等于本窗口 target，
//!   `connectionKey` 必须等于当前连接，否则 `browser_session_changed` /
//!   `browser_connection_changed`；main 可指定 target。`action` 必须是
//!   [`VIEWER_ACTIONS`] 白名单枚举，其余一律 `browser_action_invalid`。
//! - 服务 token 只存宿主 state（`HostConnection` 不实现 `Serialize`，也没有任何
//!   命令/事件返回它）；viewer 只拿 CSPRNG 生成的 32B hex 不透明 connectionKey。
//!   连接身份变化（与 Electron `connectionIdentity` 同字段哈希）时清空 target、
//!   销毁旧 viewer，并只向 main 发 `browser:connection-changed`（payload 仅
//!   布尔状态/原因，不含 token）。
//! - sessionPath 只接受服务 `native:<session-id>` 不透明身份（见 [`native_session`]）；
//!   **拒绝**文件系统路径形态（legacy JSONL 绝对路径），因此 renderer 无法借
//!   sessionPath 指定任意本机文件。若未来需要支持绝对路径，必须先 canonicalize
//!   并证明其位于本机 `LINGXI_HOME`（`{home}/sessions` 域）内、非 symlink、已存在，
//!   否则 fail closed——本版不开启该路径。
//! - `target.url` 只允许 `http`/`https` 且无 userinfo（`reqwest::Url` 严格解析）；
//!   `tabId` 拒绝空白/`*`/`?`/控制字符。renderer **不能**传服务地址或白名单
//!   覆盖：baseUrl/token 只来自 main 的 `set_browser_connection`，请求 options
//!   没有地址字段（`deny_unknown_fields`）。
//! - 关闭 viewer 只销毁窗口/清 target，**绝不**发 stop/revoke；急停只能是
//!   `rust_browser_request(..., "stop")` 显式发起的服务端事务。
//! - HTTP：只发往已登记的 loopback baseUrl，30s 超时、`redirect::Policy::none()`、
//!   `Bearer` 头；错误词表沿用 Electron `rust-browser-control.cjs`。
//!
//! ## 宿主注册清单（由 r09-host-core/Lead 合并，本文件不自行注册）
//! 1. `pub mod browser_viewer;`（`desktop/src-tauri/src/lib.rs`）。
//! 2. `.manage(browser_viewer::BrowserViewerState::default())`。
//! 3. `invoke_handler(tauri::generate_handler![...])` 增加 [`INVOKE_COMMANDS`]
//!    五个命令（Rust 侧 snake_case；camelCase ↔ Tauri 命令名的映射由
//!    DesktopHost-Tauri 层负责，例如 `rust_browser_request` ↔ `rustBrowserRequest`）。
//! 4. `desktop/src-tauri/build.rs` 的 `AppManifest::commands([...])` 增加同五个
//!    命令名（T06 四份集合一致性检查：invoke_handler / AppManifest::commands /
//!    `permissions/autogenerated/*.toml` / `capabilities/*.json`）。
//! 5. `capabilities/main.json`（label `main`）授予：
//!    `allow-set-browser-connection`、`allow-open-browser-viewer`、
//!    `allow-rust-browser-request`、`allow-close-browser-viewer`。
//! 6. 新增 `capabilities/browser-viewer.json`（windows `["browser-viewer"]`），仅授予：
//!    `core:default`（窗口自控）、`allow-get-browser-viewer-context`、
//!    `allow-rust-browser-request`、`allow-close-browser-viewer`；**不给**
//!    文件写/shell/任意 HTTP/网络命令。
//! 7. T01 构建产物提供 `browser-viewer.html?mode=native` 入口（`vite.config.ts`
//!    的 `browser-viewer` entry，复用现有 React `BrowserViewerApp` 的 native
//!    模式；不要用 main 的 `index.html`）。
//!
//! 说明：本文件当前未被 `lib.rs` 声明，因而不参与编译；合并注册点时若
//! Tauri/依赖 API 有出入，以 host-core 的 Cargo.toml 版本为准调整。

