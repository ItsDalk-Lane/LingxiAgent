/// The name of the first module whose `matches` accepts this model view —
/// the single dispatch decision (the golden suite pins it per scenario).
pub fn matched_module(view: &ModelView) -> Option<&'static str> {
    MODULES
        .iter()
        .find(|module| (module.matches)(view))
        .map(|module| module.name)
}

/// Run the compat layer for one dispatch: the FIRST matching module's
/// `apply`; no match → the payload passes through untouched (the incumbent
/// center-layer behavior).
pub fn apply(
    payload: Value,
    view: &ModelView,
    options: &CompatOptions,
) -> Result<Value, ProtocolError> {
    match MODULES.iter().find(|module| (module.matches)(view)) {
        Some(module) => (module.apply)(payload, view, options),
        None => Ok(payload),
    }
}

/// The adapter-side seam: apply the compat layer to a rendered envelope
/// when the call carries a compat context. `None` is the byte-exact
/// golden/diagnostic path (the T03/T04 harnesses) — no module runs and the
/// payload passes through untouched.
pub fn apply_for_call(
    payload: Value,
    route: &ResolvedModelRoute,
    call: Option<&CompatCall>,
) -> Result<Value, ProtocolError> {
    match call {
        Some(call) => {
            let view = ModelView::of_route(route, call.hints.as_ref());
            apply(payload, &view, &call.options)
        }
        None => Ok(payload),
    }
}

