/// The capabilities-level `getThinkingFormat` (the exact chain every
/// ported module consumes; the dispatcher-level fallbacks of
/// provider-compat.ts are NOT reproduced — no ported module reads them).
pub fn thinking_format(view: &ModelView) -> Option<String> {
    if let Some(explicit) = declared_thinking_format(view) {
        return Some(explicit);
    }
    let quirks: &[String] = view.hints.map(|h| h.quirks.as_slice()).unwrap_or(&[]);
    if quirks.iter().any(|quirk| quirk == "enable_thinking") {
        return Some("qwen".to_string());
    }
    let reasoning = reasoning_declared(view);
    let api = view_api(view);
    let provider = view_provider(view);
    let id = view_id(view);
    if reasoning == Some(true) && api == "anthropic-messages" {
        return Some("anthropic".to_string());
    }
    if provider == "anthropic" && reasoning != Some(false) {
        return Some("anthropic".to_string());
    }
    if is_openrouter_endpoint(view)
        && reasoning == Some(true)
        && (api == "openai-completions" || api.is_empty())
    {
        return Some("openrouter".to_string());
    }
    if is_official_kimi_openai_endpoint(view) && reasoning == Some(true) {
        return Some("kimi".to_string());
    }
    if is_official_volcengine_endpoint(view) && reasoning == Some(true) {
        return Some("volcengine".to_string());
    }
    if is_official_deepseek_endpoint(view)
        && (reasoning == Some(true) || is_deepseek_thinking_model_id(&id))
        && (api == "openai-completions" || api.is_empty())
    {
        return Some("deepseek".to_string());
    }
    if is_official_mimo_endpoint(view) && reasoning == Some(true) {
        return Some("qwen-chat-template".to_string());
    }
    if is_official_zhipu_endpoint(view)
        && reasoning == Some(true)
        && matches!(api.as_str(), "openai-completions" | "openai-responses" | "")
    {
        return Some("zhipu".to_string());
    }
    if is_mimo_openai_protocol_model(view) {
        return Some("qwen-chat-template".to_string());
    }
    None
}

/// The capabilities-level `getReasoningProfile` (verbatim chain).
pub fn reasoning_profile(view: &ModelView) -> Option<String> {
    if let Some(explicit) = declared_reasoning_profile(view) {
        return Some(explicit);
    }
    let reasoning = reasoning_declared(view);
    let id = view_id(view);
    let api = view_api(view);
    if is_openrouter_endpoint(view) {
        if reasoning == Some(true) && is_anthropic_adaptive_only_model_id(&id) {
            return Some("openrouter-anthropic-adaptive".to_string());
        }
        return None;
    }
    if reasoning == Some(true)
        && is_anthropic_adaptive_only_model_id(&id)
        && thinking_format(view).as_deref() == Some("anthropic")
    {
        return Some("anthropic-adaptive-only".to_string());
    }
    if is_official_mimo_endpoint(view)
        && reasoning == Some(true)
        && matches!(api.as_str(), "openai-completions" | "openai-responses" | "")
    {
        return Some("mimo-openai".to_string());
    }
    if is_official_zhipu_endpoint(view)
        && reasoning == Some(true)
        && matches!(api.as_str(), "openai-completions" | "openai-responses" | "")
    {
        return Some("zhipu-openai".to_string());
    }
    if is_official_kimi_openai_endpoint(view) && reasoning == Some(true) {
        return Some("kimi-openai".to_string());
    }
    if is_official_deepseek_endpoint(view) {
        if !is_deepseek_v4_model_id(&id) {
            return None;
        }
        if api == "anthropic-messages" {
            return Some("deepseek-v4-anthropic".to_string());
        }
        if api == "openai-responses" {
            return Some("deepseek-v4-responses".to_string());
        }
        if api == "openai-completions" || api.is_empty() {
            return Some("deepseek-v4-openai".to_string());
        }
        // Other APIs fall THROUGH to the mimo tail (incumbent-verbatim).
    }
    if is_mimo_openai_protocol_model(view) {
        Some("mimo-openai".to_string())
    } else {
        None
    }
}

/// `getOutputThinkingComposition`: explicit declaration → deepseek-official
/// baseline → wire-family default.
fn output_thinking_composition(view: &ModelView) -> &'static str {
    if let Some(explicit) = view.hints.and_then(|hints| hints.output_includes_thinking) {
        return if explicit { "included" } else { "separate" };
    }
    if is_official_deepseek_endpoint(view) {
        return "separate";
    }
    match view_api(view).as_str() {
        "anthropic-messages"
        | "google-generative-ai"
        | "google-vertex"
        | "openai-responses"
        | "openai-codex-responses"
        | "azure-openai-responses" => "included",
        _ => "separate",
    }
}

