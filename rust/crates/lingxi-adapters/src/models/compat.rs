    pub fn matches(view: &ModelView) -> bool {
        reasoning_profile(view).as_deref() == Some("openrouter-anthropic-adaptive")
    }

    /// `isThinkingOff` over a JSON value: `false` → true; strings lower (NO
    /// trim) in {off, none, disabled}; everything else → false.
    fn is_thinking_off_value(value: Option<&Value>) -> bool {
        match value {
            Some(Value::Bool(false)) => true,
            Some(Value::String(s)) => matches!(lower(s).as_str(), "off" | "none" | "disabled"),
            _ => false,
        }
    }

