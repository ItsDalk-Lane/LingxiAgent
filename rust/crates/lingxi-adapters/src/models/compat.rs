/// zhipu.ts — GLM thinking control + replay preservation flags.
mod zhipu {
    use super::*;

    pub fn matches(view: &ModelView) -> bool {
        if declared_thinking_format(view).as_deref() == Some("zhipu") {
            return true;
        }
        let provider = view_provider(view);
        let base = view_base_url(view);
        provider == "zhipu"
            || provider == "zhipu-coding"
            || base.contains("open.bigmodel.cn")
            || (base.contains("api.z.ai")
                && (base.contains("/api/paas/v4") || base.contains("/api/coding/paas/v4")))
    }

    /// `isThinkingOff`: false → true; null → false; else lower in
    /// {"", "none", "off", "disabled"} (NO trim).
    fn is_thinking_off(level: Option<&str>) -> bool {
        match level {
            None => false,
            Some(value) => matches!(lower(value).as_str(), "" | "none" | "off" | "disabled"),
        }
    }

    fn is_opencode_go_endpoint(view: &ModelView) -> bool {
        view_provider(view) == "opencode-go" || view_base_url(view).contains("opencode.ai/zen/go")
    }

    fn has_assistant_tool_call_history(payload: &Value) -> bool {
        payload
            .get("messages")
            .and_then(Value::as_array)
            .is_some_and(|messages| {
                messages.iter().any(|message| {
                    message.get("role").and_then(Value::as_str) == Some("assistant")
                        && message
                            .get("tool_calls")
                            .and_then(Value::as_array)
                            .is_some_and(|calls| !calls.is_empty())
                })
            })
    }

    fn has_assistant_reasoning_history(payload: &Value) -> bool {
        payload
            .get("messages")
            .and_then(Value::as_array)
            .is_some_and(|messages| {
                messages.iter().any(|message| {
                    message.get("role").and_then(Value::as_str) == Some("assistant")
                        && message
                            .get("reasoning_content")
                            .and_then(Value::as_str)
                            .is_some_and(|text| !text.is_empty())
                })
            })
    }

    #[derive(PartialEq)]
    enum Replay {
        Clear,
        Preserve,
    }

    /// `resolveReasoningReplay`: the explicit option wins; otherwise the
    /// payload's own `thinking.clear_thinking` decides; default preserve.
    fn resolve_reasoning_replay(payload: &Value, options: &CompatOptions) -> Replay {
        if let Some(value) = options.reasoning_replay.as_deref().map(lower) {
            match value.as_str() {
                "clear" | "none" | "strip" => return Replay::Clear,
                "preserve" | "replay" => return Replay::Preserve,
                _ => {}
            }
        }
        if let Some(clear) = payload
            .get("thinking")
            .and_then(Value::as_object)
            .and_then(|thinking| thinking.get("clear_thinking"))
        {
            return if clear == &Value::Bool(true) {
                Replay::Clear
            } else {
                Replay::Preserve
            };
        }
        Replay::Preserve
    }

    /// `normalizeTools`: drop `strict` at the tool and the
    /// `tool.function` level.
    fn normalize_tools(tools: &Value) -> Value {
        let Some(items) = tools.as_array() else {
            return tools.clone();
        };
        Value::Array(
            items
                .iter()
                .map(|tool| {
                    let mut next = tool.clone();
                    if let Some(obj) = next.as_object_mut() {
                        obj.remove("strict");
                        if let Some(function) =
                            obj.get_mut("function").and_then(Value::as_object_mut)
                        {
                            function.remove("strict");
                        }
                    }
                    next
                })
                .collect(),
        )
    }

    pub fn apply(
        payload: Value,
        view: &ModelView,
        options: &CompatOptions,
    ) -> Result<Value, ProtocolError> {
        let mut next = payload;
        // normalizeMaxTokenField
        if has_own(&next, "max_completion_tokens") {
            let obj = next.as_object_mut().expect("payload object");
            if !obj.contains_key("max_tokens") {
                let value = obj["max_completion_tokens"].clone();
                obj.insert("max_tokens".to_string(), value);
            }
            obj.remove("max_completion_tokens");
        }
        {
            let obj = next.as_object_mut().expect("payload object");
            obj.remove("store");
            obj.remove("stream_options");
        }
        if let Some(tools) = next.get("tools").cloned() {
            let normalized = normalize_tools(&tools);
            if normalized != tools {
                next["tools"] = normalized;
            }
        }
        // normalizeThinking
        let off = options.mode == CompatMode::Utility
            || is_thinking_off(options.reasoning_level.as_deref())
            || next
                .get("thinking")
                .and_then(|t| t.get("type"))
                .and_then(Value::as_str)
                == Some("disabled")
            || next.get("enable_thinking") == Some(&Value::Bool(false));
        let wants_thinking = !off
            && (has_own(&next, "reasoning_effort")
                || next.get("enable_thinking") == Some(&Value::Bool(true))
                || reasoning_declared(view) == Some(true)
                || next
                    .get("thinking")
                    .and_then(|t| t.get("type"))
                    .and_then(Value::as_str)
                    == Some("enabled"));
        if !off && !wants_thinking && !has_own(&next, "reasoning_effort") {
            return Ok(next);
        }
        {
            let obj = next.as_object_mut().expect("object");
            obj.remove("reasoning_effort");
            obj.remove("enable_thinking");
        }
        if off {
            next["thinking"] = json!({"type": "disabled"});
            strip_payload_reasoning_content(&mut next);
            return Ok(next);
        }
        // The replay decision reads the ORIGINAL payload's
        // `thinking.clear_thinking` (incumbent-verbatim) — compute it
        // BEFORE the thinking block is normalized.
        let replay = resolve_reasoning_replay(&next, options);
        next["thinking"] = json!({"type": "enabled"});
        let can_send_clear_thinking = !is_opencode_go_endpoint(view);
        let has_tool_calls = has_assistant_tool_call_history(&next);
        if replay == Replay::Clear {
            if can_send_clear_thinking {
                next["thinking"]["clear_thinking"] = Value::Bool(true);
            }
            strip_payload_reasoning_content(&mut next);
        } else if can_send_clear_thinking
            && (has_tool_calls || has_assistant_reasoning_history(&next))
        {
            next["thinking"]["clear_thinking"] = Value::Bool(false);
        }
        if has_tool_calls {
            ensure_payload_assistant_content(&mut next);
        }
        Ok(next)
    }
}

/// volcengine.ts — Volcengine Ark ChatCompletions thinking control
/// (`thinking.type` plus the reduced `reasoning_effort` vocabulary).
mod volcengine {
    use super::*;

    pub fn matches(view: &ModelView) -> bool {
        // `lower(model.compat?.thinkingFormat) === "volcengine"` (no trim —
        // the declared value is matched verbatim-lowercased).
        if declared_thinking_format(view).as_deref() == Some("volcengine") {
            return true;
        }
        let provider = view_provider(view);
        if provider == "volcengine" || provider == "volcengine-coding" {
            return true;
        }
        let host = view_host(view);
        host == "ark.cn-beijing.volces.com" || host.ends_with(".volces.com")
    }

    /// `isThinkingOff`: null → false; else lower (NO trim) in
    /// {"", "none", "off", "disabled"} (an empty level IS disabling).
    fn is_thinking_off(level: Option<&str>) -> bool {
        match level {
            None => false,
            Some(value) => matches!(lower(value).as_str(), "" | "none" | "off" | "disabled"),
        }
    }

    /// `reasoningEffortForLevel` over the already-lowered text.
    fn effort_for_normalized(normalized: &str) -> Option<&'static str> {
        match normalized {
            "minimal" => Some("minimal"),
            "low" => Some("low"),
            "medium" | "auto" => Some("medium"),
            "high" | "xhigh" | "max" => Some("high"),
            _ => None,
        }
    }

    fn effort_for_level(level: Option<&str>) -> Option<&'static str> {
        effort_for_normalized(&lower(level.unwrap_or("")))
    }

    /// `reasoningEffortForLevel(payload.reasoning_effort)` — non-strings
    /// lower to "" (no effort).
    fn effort_for_value(value: Option<&Value>) -> Option<&'static str> {
        let text = match value {
            Some(Value::String(s)) => lower(s),
            _ => String::new(),
        };
        effort_for_normalized(&text)
    }

    fn has_thinking_controls(payload: &Value) -> bool {
        has_own(payload, "thinking")
            || has_own(payload, "reasoning_effort")
            || has_own(payload, "enable_thinking")
    }

    fn should_disable_thinking(payload: &Value, view: &ModelView, options: &CompatOptions) -> bool {
        options.mode == CompatMode::Utility
            || is_thinking_off(options.reasoning_level.as_deref())
            || payload
                .get("thinking")
                .and_then(|t| t.get("type"))
                .and_then(Value::as_str)
                == Some("disabled")
            || payload.get("enable_thinking") == Some(&Value::Bool(false))
            || (reasoning_declared(view) == Some(false) && has_thinking_controls(payload))
    }

    fn should_enable_thinking(payload: &Value, view: &ModelView, options: &CompatOptions) -> bool {
        reasoning_declared(view) == Some(true)
            || payload
                .get("thinking")
                .and_then(|t| t.get("type"))
                .and_then(Value::as_str)
                == Some("enabled")
            || payload.get("enable_thinking") == Some(&Value::Bool(true))
            || has_own(payload, "reasoning_effort")
            || effort_for_level(options.reasoning_level.as_deref()).is_some()
    }

    fn disable_thinking(payload: &mut Value) {
        {
            let obj = payload.as_object_mut().expect("payload object");
            obj.remove("reasoning_effort");
            obj.remove("enable_thinking");
            obj.insert("thinking".to_string(), json!({"type": "disabled"}));
        }
        strip_payload_reasoning_content(payload);
    }

    fn enable_thinking(payload: &mut Value, options: &CompatOptions) {
        let obj = payload.as_object_mut().expect("payload object");
        obj.remove("enable_thinking");
        obj.insert("thinking".to_string(), json!({"type": "enabled"}));
        // The request level wins; otherwise an already-present
        // `reasoning_effort` is re-mapped into the Volcengine vocabulary.
        let effort = effort_for_level(options.reasoning_level.as_deref()).or_else(|| {
            if has_own(payload, "reasoning_effort") {
                effort_for_value(payload.get("reasoning_effort"))
            } else {
                None
            }
        });
        let obj = payload.as_object_mut().expect("payload object");
        match effort {
            Some(effort) => {
                obj.insert(
                    "reasoning_effort".to_string(),
                    Value::String(effort.to_string()),
                );
            }
            None => {
                obj.remove("reasoning_effort");
            }
        }
    }

    pub fn apply(
        payload: Value,
        view: &ModelView,
        options: &CompatOptions,
    ) -> Result<Value, ProtocolError> {
        // TS guards on `typeof payload === "object"` (arrays pass but only
        // ever degenerate); the renderers emit objects only.
        if !payload.is_object() {
            return Ok(payload);
        }
        if should_disable_thinking(&payload, view, options) {
            // The guard: without declared reasoning AND without existing
            // thinking controls there is nothing to disable — pass through.
            if reasoning_declared(view) != Some(true) && !has_thinking_controls(&payload) {
                return Ok(payload);
            }
            let mut next = payload;
            disable_thinking(&mut next);
            return Ok(next);
        }
        if !should_enable_thinking(&payload, view, options) {
            return Ok(payload);
        }
        let mut next = payload;
        enable_thinking(&mut next, options);
        Ok(next)
    }
}

/// agnes.ts — Agnes AI thinking-field strip (the provider has no structured
/// reasoning carrier; every thinking control and reasoning trace is removed).
mod agnes {
    use super::*;

    const THINKING_PAYLOAD_FIELDS: [&str; 5] = [
        "reasoning_effort",
        "thinking",
        "reasoning",
        "enable_thinking",
        "chat_template_kwargs",
    ];
    const THINKING_MESSAGE_FIELDS: [&str; 3] = ["reasoning_content", "reasoning", "thinking"];

    pub fn matches(view: &ModelView) -> bool {
        // agnes.ts `lower` trims.
        if lower_trim(view.provider) == "agnes" {
            return true;
        }
        let host = view_host(view);
        host == "agnes-ai.com" || host.ends_with(".agnes-ai.com")
    }

    /// `stripThinkingBlocks`: drop content blocks that are thinking markers.
    /// Returns Some(replacement) only when something was stripped.
    fn strip_thinking_blocks(content: &Value) -> Option<Value> {
        let items = content.as_array()?;
        let mut next = Vec::with_capacity(items.len());
        let mut changed = false;
        for block in items {
            let drop = block.as_object().is_some_and(|obj| {
                obj.get("type")
                    .and_then(Value::as_str)
                    .is_some_and(|t| matches!(lower_trim(t).as_str(), "thinking" | "reasoning"))
                    || obj.contains_key("reasoning_content")
                    || obj.contains_key("thinking")
            });
            if drop {
                changed = true;
            } else {
                next.push(block.clone());
            }
        }
        changed.then_some(Value::Array(next))
    }

    /// `stripMessageThinking`: message-level thinking fields + thinking
    /// content blocks. Returns Some(replacement) only when changed.
    fn strip_message_thinking(message: &Value) -> Option<Value> {
        let obj = message.as_object()?;
        let mut next = obj.clone();
        let mut changed = false;
        for field in THINKING_MESSAGE_FIELDS {
            if next.remove(field).is_some() {
                changed = true;
            }
        }
        if let Some(content) = obj.get("content") {
            if let Some(stripped) = strip_thinking_blocks(content) {
                next.insert("content".to_string(), stripped);
                changed = true;
            }
        }
        changed.then_some(Value::Object(next))
    }

    pub fn apply(
        payload: Value,
        _view: &ModelView,
        _options: &CompatOptions,
    ) -> Result<Value, ProtocolError> {
        let Some(obj) = payload.as_object() else {
            return Ok(payload);
        };
        let mut next = obj.clone();
        for field in THINKING_PAYLOAD_FIELDS {
            next.remove(field);
        }
        if let Some(Value::Array(messages)) = obj.get("messages") {
            let mut any_changed = false;
            let mut stripped = Vec::with_capacity(messages.len());
            for message in messages {
                match strip_message_thinking(message) {
                    Some(message) => {
                        any_changed = true;
                        stripped.push(message);
                    }
                    None => stripped.push(message.clone()),
                }
            }
            if any_changed {
                next.insert("messages".to_string(), Value::Array(stripped));
            }
        }
        Ok(Value::Object(next))
    }
}

/// openrouter.ts — OpenRouter-hosted Claude 5 adaptive-only models (the
