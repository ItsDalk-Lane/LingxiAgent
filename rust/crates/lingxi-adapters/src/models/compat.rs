#[derive(Debug, Clone, Default)]
pub struct CompatCall {
    pub hints: Option<RouteCompatHints>,
    pub options: CompatOptions,
}

/// The model view the derivation chain and the module matchers read — the
/// TS `model` object's Rust-facing subset. Every field traces to the
/// resolved route (never guessed); `hints` is the route binding's declared
/// compat block.
#[derive(Debug, Clone, Copy)]
pub struct ModelView<'a> {
    pub provider: &'a str,
    pub model_id: &'a str,
    pub base_url: &'a str,
    /// The protocol family config name (`openai-completions`, ...).
    pub api: &'a str,
    pub hints: Option<&'a RouteCompatHints>,
}

impl<'a> ModelView<'a> {
    pub fn of_route(route: &'a ResolvedModelRoute, hints: Option<&'a RouteCompatHints>) -> Self {
        Self {
            provider: &route.provider,
            model_id: &route.model,
            base_url: &route.endpoint,
            api: route.protocol.config_name(),
            hints,
        }
    }
}

