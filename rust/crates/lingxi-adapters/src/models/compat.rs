/// ollama.ts — the structured-output `response_format` bridge and the
/// `num_ctx` context-window bridge (capped at 1 MiB).
mod ollama {
    use super::*;

    /// The incumbent num_ctx ceiling (1 MiB).
    const MAX_SAFE_CONTEXT_WINDOW: u64 = 1_048_576;

    pub fn matches(view: &ModelView) -> bool {
        // ollama.ts `lower` does NOT trim.
        lower(view.provider) == "ollama"
    }

    pub fn apply(
        payload: Value,
        view: &ModelView,
        options: &CompatOptions,
    ) -> Result<Value, ProtocolError> {
        let Some(obj) = payload.as_object() else {
            return Ok(payload);
        };
        let mut next = obj.clone();
        // `options.responseSchema` — any JSON object/array (`typeof object`).
        if let Some(schema) = options
            .response_schema
            .as_ref()
            .filter(|schema| schema.is_object() || schema.is_array())
        {
            next.insert(
                "response_format".to_string(),
                json!({
                    "type": "json_schema",
                    "json_schema": {
                        "name": "structured_output",
                        "schema": schema,
                        "strict": true,
                    },
                }),
            );
        }
        // The num_ctx bridge (the config plane already guarantees a positive
        // integer; the 1 MiB ceiling is the remaining rule).
        if let Some(window) = view.hints.and_then(|hints| hints.context_window) {
            if window <= MAX_SAFE_CONTEXT_WINDOW {
                let mut opts = next
                    .get("options")
                    .and_then(Value::as_object)
                    .cloned()
                    .unwrap_or_default();
                opts.insert("num_ctx".to_string(), Value::from(window));
                next.insert("options".to_string(), Value::Object(opts));
            }
        }
        Ok(Value::Object(next))
    }
}

