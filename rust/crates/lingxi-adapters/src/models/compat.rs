/// The per-call option set of the compat layer (the TS `options` argument
/// of `normalizeProviderPayload`/module `apply`). Production constructs it
/// through [`CompatOptions::for_operation`]; the reasoning level / response
/// schema / replay policy / budget sources stay `None` until their owner
/// stages land (session thinking level: T07; structured output: T06).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct CompatOptions {
    pub mode: CompatMode,
    /// The normalized request thinking level (`off|minimal|low|medium|
    /// high|xhigh|max`, lowercase). The TS center layer normalizes before
    /// dispatch; this layer consumes the normalized value verbatim.
    pub reasoning_level: Option<String>,
    /// The structured-output schema (ollama `response_format` bridge).
    pub response_schema: Option<Value>,
    /// The reasoning replay policy override (`clear|preserve|...`, zhipu).
    pub reasoning_replay: Option<String>,
    /// Anthropic max-effort budget provenance (`user|system` veto the
    /// implicit-cap raise).
    pub output_budget_source: Option<String>,
    /// Alias half of the TS `outputBudgetSource || maxTokensSource` read.
    pub max_tokens_source: Option<String>,
}

/// Chat vs utility mode (the TS `options.mode`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum CompatMode {
    #[default]
    Chat,
    Utility,
}

impl CompatOptions {
    /// The production option set of one resolved route: the mode follows
    /// the operation (chat → chat, auxiliary slots → utility); every other
    /// knob is `None` (no Rust-side source yet — registered above).
    pub fn for_operation(operation: &ModelOperation) -> Self {
        Self {
            mode: match operation {
                ModelOperation::Chat => CompatMode::Chat,
                ModelOperation::Auxiliary(_) => CompatMode::Utility,
                _ => CompatMode::Chat,
            },
            ..Self::default()
        }
    }
}

/// Everything an adapter needs to run the compat layer for one dispatch:
