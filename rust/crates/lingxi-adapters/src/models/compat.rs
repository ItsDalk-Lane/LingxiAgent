/// `stripReasoningContent`: remove the `reasoning_content` key from every
/// message object that carries it (any role — incumbent-verbatim).
fn strip_reasoning_content(messages: &mut [Value]) {
    for message in messages.iter_mut() {
        if let Some(obj) = message.as_object_mut() {
            obj.remove("reasoning_content");
        }
    }
}

/// reasoning-content-replay.ts `hasToolCalls`: a non-empty `tool_calls`
/// array, or a content part with `type: "toolCall"`.
fn message_has_tool_calls(message: &Value) -> bool {
    if message
        .get("tool_calls")
        .and_then(Value::as_array)
        .is_some_and(|calls| !calls.is_empty())
    {
        return true;
    }
    message
        .get("content")
        .and_then(Value::as_array)
        .is_some_and(|content| {
            content
                .iter()
                .any(|block| block.get("type").and_then(Value::as_str) == Some("toolCall"))
        })
}

/// `normalizeAssistantContent`: strings stay; null/missing/non-container
/// values become `""`; a parts array concatenates its `type:"text"` parts'
/// text (no separator).
fn normalize_assistant_content(content: Option<&Value>) -> Value {
    match content {
        Some(Value::String(text)) => Value::String(text.clone()),
        Some(Value::Array(parts)) => Value::String(
            parts
                .iter()
                .filter_map(|block| {
                    if block.get("type").and_then(Value::as_str) == Some("text") {
                        block
                            .get("text")
                            .and_then(Value::as_str)
                            .map(str::to_string)
                    } else {
                        None
                    }
                })
                .collect(),
        ),
        _ => Value::String(String::new()),
    }
}

/// `ensureAssistantContentForToolCalls`: every assistant message with tool
/// calls gets a string `content` (null/missing → `""`, parts → joined
/// text); messages already compliant stay untouched.
fn ensure_assistant_content_for_tool_calls(messages: &mut [Value]) {
    for message in messages.iter_mut() {
        if message.get("role").and_then(Value::as_str) != Some("assistant") {
            continue;
        }
        if !message_has_tool_calls(message) {
            continue;
        }
        let current = message.get("content").cloned();
        let normalized = normalize_assistant_content(current.as_ref());
        if current.as_ref() != Some(&normalized) {
            message["content"] = normalized;
        }
    }
}

fn payload_messages_mut(payload: &mut Value) -> Option<&mut Vec<Value>> {
    payload.get_mut("messages").and_then(Value::as_array_mut)
}

fn strip_payload_reasoning_content(payload: &mut Value) {
    if let Some(messages) = payload_messages_mut(payload) {
        strip_reasoning_content(messages);
    }
}

fn ensure_payload_assistant_content(payload: &mut Value) {
    if let Some(messages) = payload_messages_mut(payload) {
        ensure_assistant_content_for_tool_calls(messages);
    }
}

