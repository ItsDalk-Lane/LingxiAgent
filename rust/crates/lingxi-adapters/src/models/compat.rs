//! The provider compat layer (R05-T05): a faithful port of the incumbent
//! `core/provider-compat/*` per-provider payload patches plus the
//! `shared/model-capabilities.ts` derivation chain those patches read.
//!
//! Scope and discipline:
//! - Dispatch is FIRST-MATCH-WINS over the same registry order as the
//!   incumbent `PROVIDER_MODULES`, minus the two modules this runtime
//!   cannot serve (see below). [`matched_module`] is the single dispatch
//!   decision; [`apply`] runs exactly that module's patch.
//! - The TS modules throw on protocol-impossible requests (adaptive-only
//!   models asked to disable thinking). The port maps a throw to a loud
//!   [`ErrorCode::InvalidMessage`] non-retryable refusal carrying the
//!   incumbent message verbatim — never a fabricated payload.
//! - Fidelity is pinned by `tests/golden-compat/*.json`: every golden is
//!   GENERATED by running the incumbent TS modules (node type-stripping)
//!   on the same (model, payload, options) triple, so a drift between this
//!   port and the incumbent breaks the suite loudly.
//!
//! Registered scope decisions (R05-T05 ledger, INTERFACE_EVOLUTION §25):
//! - `longcat` is NOT ported: its only action is DISABLING thinking
//!   (utility mode / `reasoningLevel` off / pre-existing thinking controls
//!   in the payload) and stripping replayed reasoning
//!   (core/provider-compat/longcat.ts `shouldDisableThinking` /
//!   `disableThinking`). None of those triggers can fire on this pipeline —
//!   production `CompatOptions` carry `reasoning_level: None` (the session
//!   thinking level is the T07 owner) and the Rust renderers never emit
//!   `thinking` / `enable_thinking` / `reasoning_effort` fields — so the
//!   module is the identity function here.
//! - `openai-input-audio` is NOT ported: it normalizes `input_audio`
//!   message parts (core/provider-compat/input-audio.ts), and
//!   `ModelTurnInput` carries text-only content blocks today (media and
//!   resource-reference inputs are the R05-T06 owner) — no payload ever
//!   contains an audio part. `openai-video-url` is likewise unported: it
//!   sits OUTSIDE the dispatch registry (centralized capability handling,
//!   never selected by `PROVIDER_MODULES`). The center-layer generic
//!   patches (stripEmptyTools / stripIncompatibleThinking /
//!   normalizeAutoReasoningEffort / stripDisabledReasoningEffort /
//!   stripOrphanToolMessages / reasoning-replay center validation / media
//!   marker stripping) are likewise not ported: the Rust renderers never
//!   emit `thinking` / `reasoning_effort` / empty `tools` / SDK-serialized
//!   orphan shapes, so those patches are the identity function on this
//!   pipeline.
//! - The `deepseek` roleplay-marker injection is not ported: its trigger
//!   (`options.deepseekRoleplayReasoningPatch`) is a session/agent-runtime
//!   product setting with no Rust-side source (owner: persona/session
//!   layer). Its TS default is OFF, which is the behavior here.
//! - `getModelText` reads only the model id (the TS original also scans
//!   name/model/modelId aliases the config plane does not carry).
//! - `model.maxOutput` (the `maxTokens || maxOutput` fallback) is not
//!   representable in the config compat block; declare `maxTokens`.

