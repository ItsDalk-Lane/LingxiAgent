/// JS `\b` before a word char: the preceding char is absent or non-word
/// (`[A-Za-z0-9_]`).
fn word_boundary_before(text: &str, byte_index: usize) -> bool {
    if byte_index == 0 {
        return true;
    }
    let prev = text[..byte_index]
        .chars()
        .next_back()
        .expect("non-empty prefix");
    !prev.is_ascii_alphanumeric() && prev != '_'
}

/// The incumbent `/\bmimo[-_]?v\d/` over the (already lowercased) text.
fn has_mimo_family_marker(text: &str) -> bool {
    for (start, _) in text.match_indices("mimo") {
        if !word_boundary_before(text, start) {
            continue;
        }
        let rest = &text[start + "mimo".len()..];
        let rest = rest
            .strip_prefix('-')
            .or_else(|| rest.strip_prefix('_'))
            .unwrap_or(rest);
        let mut chars = rest.chars();
        if chars.next() == Some('v') && chars.next().is_some_and(|c| c.is_ascii_digit()) {
            return true;
        }
    }
    false
}

/// The incumbent `/\bmimo[-_]?v\d+(?:[._-]\d+)?[-_]tts\b/` (the TTS-variant
/// exclusion). Greedy sequential matching is exact here: every quantified
/// class is disjoint from what follows it, so no backtracking path exists
/// that the sequential scan would miss.
fn has_mimo_tts_marker(text: &str) -> bool {
    for (start, _) in text.match_indices("mimo") {
        if !word_boundary_before(text, start) {
            continue;
        }
        let rest = &text[start + "mimo".len()..];
        let rest = rest
            .strip_prefix('-')
            .or_else(|| rest.strip_prefix('_'))
            .unwrap_or(rest);
        let Some(rest) = rest.strip_prefix('v') else {
            continue;
        };
        let digits = rest.bytes().take_while(|b| b.is_ascii_digit()).count();
        if digits == 0 {
            continue;
        }
        let rest = &rest[digits..];
        // (?:[._-]\d+)?
        let rest = match rest.strip_prefix(['.', '_', '-']) {
            Some(after_sep) => {
                let more = after_sep.bytes().take_while(|b| b.is_ascii_digit()).count();
                if more > 0 {
                    &after_sep[more..]
                } else {
                    rest
                }
            }
            None => rest,
        };
        let Some(rest) = rest.strip_prefix('-').or_else(|| rest.strip_prefix('_')) else {
            continue;
        };
        let Some(rest) = rest.strip_prefix("tts") else {
            continue;
        };
        // `\b` after `tts` (a word char): next char absent or non-word.
        match rest.chars().next() {
            None => return true,
            Some(c) if !c.is_ascii_alphanumeric() && c != '_' => return true,
            _ => continue,
        }
    }
    false
}

/// `isMimoFamilyModel` over the model text (the Rust view's text is the
