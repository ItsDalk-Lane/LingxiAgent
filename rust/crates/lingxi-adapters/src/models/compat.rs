    #[test]
    fn anthropic_max_effort_raises_the_implicit_one_third_cap() {
        let hints = RouteCompatHints {
            max_tokens: Some(96_000),
            ..RouteCompatHints::default()
        };
        let v = view(
            "anthropic",
            "claude-opus-5",
            "https://api.anthropic.com",
            "anthropic-messages",
            Some(&hints),
        );
        let payload = json!({
            "model": "claude-opus-5",
            "messages": [{"role": "user", "content": "hi"}],
            "max_tokens": 32_000
        });
        let out = apply(payload, &v, &chat_options(Some("xhigh"))).expect("ok");
        assert_eq!(
            out["thinking"],
            json!({"type": "adaptive", "display": "summarized"})
        );
        assert_eq!(out["output_config"], json!({"effort": "max"}));
        // 32000 == 96000/3 (implicit) → raised toward min(96000, 64000).
        assert_eq!(out["max_tokens"], json!(64_000));
        // A user-sourced budget vetoes the raise.
        let payload = json!({
            "model": "claude-opus-5",
            "messages": [{"role": "user", "content": "hi"}],
            "max_tokens": 32_000
        });
        let mut options = chat_options(Some("xhigh"));
        options.output_budget_source = Some("user".to_string());
        let out = apply(payload, &v, &options).expect("ok");
        assert_eq!(out["max_tokens"], json!(32_000));
    }

